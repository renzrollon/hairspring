# --------------------------------------------------------------------------- YAML subset


class YamlError(ValueError):
    pass


_BOOL = {"true": True, "yes": True, "on": True, "false": False, "no": False, "off": False}
_INT = re.compile(r"^[-+]?(?:0|[1-9][0-9_]*)$")
_FLOAT = re.compile(r"^[-+]?(?:\d[\d_]*)?\.\d*(?:[eE][-+]?\d+)?$")
_KEY = re.compile(r"""^("(?:[^"\\]|\\.)*"|'(?:[^']|'')*'|[^\s"'#\-?:,\[\]{}&*!|>%@`][^:#]*?|-[^\s:][^:#]*?)\s*:(?:\s+(.*)|\s*)$""")
_BLOCK = re.compile(r"^([|>])([-+]?)([1-9]?)([-+]?)\s*(?:#.*)?$")


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _strip_comment(text: str) -> str:
    """Drop a trailing ``# comment`` that is outside quotes."""
    quote = None
    escaped = False
    for i, ch in enumerate(text):
        if quote:
            if escaped:
                escaped = False
            elif ch == "\\" and quote == '"':
                escaped = True
            elif ch == quote:
                quote = None
        elif ch in "\"'" and (i == 0 or text[i - 1] in " \t[{,:"):
            quote = ch
        elif ch == "#" and (i == 0 or text[i - 1] in " \t"):
            return text[:i].rstrip()
    return text.rstrip()


def _unquote(text: str, lineno: int) -> str:
    if text.startswith('"'):
        if not text.endswith('"') or len(text) < 2:
            raise YamlError(f"line {lineno}: unterminated double-quoted string")
        body = text[1:-1]
        escapes = {"n": "\n", "t": "\t", "\\": "\\", '"': '"', "/": "/", "0": "\0", " ": " ",
                   "r": "\r", "b": "\b", "e": "\x1b", "a": "\x07"}
        out, i = [], 0
        while i < len(body):
            ch = body[i]
            if ch == "\\" and i + 1 < len(body):
                nxt = body[i + 1]
                if nxt in escapes:
                    out.append(escapes[nxt])
                    i += 2
                    continue
                if nxt in "xuU":
                    size = {"x": 2, "u": 4, "U": 8}[nxt]
                    try:
                        out.append(chr(int(body[i + 2: i + 2 + size], 16)))
                    except ValueError:
                        raise YamlError(f"line {lineno}: bad escape \\{nxt}") from None
                    i += 2 + size
                    continue
                raise YamlError(f"line {lineno}: unknown escape \\{nxt}")
            out.append(ch)
            i += 1
        return "".join(out)
    if text.startswith("'"):
        if not text.endswith("'") or len(text) < 2:
            raise YamlError(f"line {lineno}: unterminated single-quoted string")
        return text[1:-1].replace("''", "'")
    return text


def _scalar(text: str, lineno: int) -> Any:
    text = text.strip()
    if not text:
        return None
    if text[0] in "\"'":
        return _unquote(text, lineno)
    if text[0] == "[":
        return _flow_seq(text, lineno)
    if text[0] == "{":
        return _flow_map(text, lineno)
    if text[0] in "&*!|>%@`":
        raise YamlError(f"line {lineno}: unsupported YAML syntax {text[0]!r} (keep frontmatter simple)")
    if re.search(r":(?:\s|$)", text):
        raise YamlError(f"line {lineno}: ': ' inside a plain value is not valid YAML; quote the value "
                        "or use a '>-' block")
    low = text.lower()
    if low in ("~", "null"):
        return None
    if low in _BOOL and text in (low, low.capitalize(), low.upper()):
        return _BOOL[low]
    if _INT.match(text):
        return int(text.replace("_", ""))
    if _FLOAT.match(text) and any(c.isdigit() for c in text):
        return float(text.replace("_", ""))
    return text


def _split_flow(body: str, lineno: int) -> List[str]:
    items, buf, quote, depth = [], [], None, 0
    for ch in body:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "\"'":
            quote = ch
        elif ch in "[{":
            depth += 1
        elif ch in "]}":
            depth -= 1
        if ch == "," and depth == 0:
            items.append("".join(buf).strip())
            buf = []
            continue
        buf.append(ch)
    if quote:
        raise YamlError(f"line {lineno}: unterminated string in flow collection")
    tail = "".join(buf).strip()
    if tail:
        items.append(tail)
    return items


def _flow_seq(text: str, lineno: int) -> List[Any]:
    if not text.endswith("]"):
        raise YamlError(f"line {lineno}: unterminated flow sequence (keep [a, b] on one line)")
    return [_scalar(item, lineno) for item in _split_flow(text[1:-1], lineno)]


def _flow_map(text: str, lineno: int) -> Dict[str, Any]:
    if not text.endswith("}"):
        raise YamlError(f"line {lineno}: unterminated flow mapping (keep {{a: b}} on one line)")
    out: Dict[str, Any] = {}
    for item in _split_flow(text[1:-1], lineno):
        key, sep, value = item.partition(":")
        if not sep:
            raise YamlError(f"line {lineno}: expected 'key: value' in flow mapping")
        out[str(_unquote(key.strip(), lineno))] = _scalar(value, lineno)
    return out


class _MiniYaml:
    """Block mappings and sequences, plain/quoted scalars, flow collections, block scalars."""

    def __init__(self, text: str, first_line: int = 1) -> None:
        if "\t" in "".join(re.findall(r"^[ \t]+", text, re.M)):
            raise YamlError("tabs are not allowed in YAML indentation")
        self.lines = text.replace("\r\n", "\n").split("\n")
        self.offset = first_line

    def lineno(self, i: int) -> int:
        return i + self.offset

    def _skip(self, i: int) -> int:
        while i < len(self.lines):
            stripped = self.lines[i].strip()
            if stripped and not stripped.startswith("#"):
                break
            i += 1
        return i

    def parse(self) -> Any:
        i = self._skip(0)
        if i >= len(self.lines):
            return None
        if self.lines[i].strip() in ("---",):
            i = self._skip(i + 1)
        value, i = self._node(i, _indent(self.lines[i]) if i < len(self.lines) else 0)
        i = self._skip(i)
        if i < len(self.lines):
            raise YamlError(f"line {self.lineno(i)}: unexpected content (check the indentation)")
        return value

    def _node(self, i: int, indent: int) -> Tuple[Any, int]:
        i = self._skip(i)
        if i >= len(self.lines):
            return None, i
        content = self.lines[i].strip()
        if content == "-" or content.startswith("- "):
            return self._seq(i, _indent(self.lines[i]))
        if _KEY.match(_strip_comment(content)):
            return self._map(i, _indent(self.lines[i]))
        value, i = self._plain_or_quoted(_strip_comment(content), i, indent - 1)
        return value, i

    def _map(self, i: int, indent: int) -> Tuple[Dict[str, Any], int]:
        out: Dict[str, Any] = {}
        while True:
            i = self._skip(i)
            if i >= len(self.lines):
                break
            line = self.lines[i]
            current = _indent(line)
            if current < indent:
                break
            if current > indent:
                raise YamlError(f"line {self.lineno(i)}: unexpected indentation")
            content = _strip_comment(line.strip())
            if content == "-" or content.startswith("- "):
                break
            m = _KEY.match(content)
            if not m:
                raise YamlError(f"line {self.lineno(i)}: expected 'key: value', got {content!r}")
            key = _unquote(m.group(1).strip(), self.lineno(i))
            if key in out:
                raise YamlError(f"line {self.lineno(i)}: duplicate key {key!r}")
            rest = (m.group(2) or "").strip()
            block = _BLOCK.match(rest)
            if block:
                out[key], i = self._block_scalar(i + 1, indent, block)
                continue
            if rest:
                out[key], i = self._plain_or_quoted(rest, i, indent)
                continue
            j = self._skip(i + 1)
            if j < len(self.lines) and _indent(self.lines[j]) > indent:
                out[key], i = self._node(j, _indent(self.lines[j]))
            elif j < len(self.lines) and _indent(self.lines[j]) == indent and (
                    self.lines[j].strip() == "-" or self.lines[j].strip().startswith("- ")):
                out[key], i = self._seq(j, indent)
            else:
                out[key], i = None, i + 1
        return out, i

    def _seq(self, i: int, indent: int) -> Tuple[List[Any], int]:
        out: List[Any] = []
        while True:
            i = self._skip(i)
            if i >= len(self.lines):
                break
            line = self.lines[i]
            current = _indent(line)
            content = line.strip()
            if current < indent or not (content == "-" or content.startswith("- ")):
                break
            if current > indent:
                raise YamlError(f"line {self.lineno(i)}: unexpected indentation")
            rest = content[1:].strip()
            if not rest:
                j = self._skip(i + 1)
                if j < len(self.lines) and _indent(self.lines[j]) > indent:
                    value, i = self._node(j, _indent(self.lines[j]))
                else:
                    value, i = None, i + 1
            elif _KEY.match(_strip_comment(rest)) and not rest.startswith(("\"", "'", "[", "{")):
                self.lines[i] = " " * (indent + 2) + rest
                value, i = self._map(i, indent + 2)
            else:
                value, i = self._plain_or_quoted(_strip_comment(rest), i, indent)
            out.append(value)
        return out, i

    def _plain_or_quoted(self, text: str, i: int, indent: int) -> Tuple[Any, int]:
        """A scalar starting on line ``i``; quoted and plain scalars may continue on more-indented lines."""
        if text[:1] in "\"'":
            quote = text[0]
            closed = self._closes(text, quote)
            parts, j = [text], i
            while not closed:
                j += 1
                if j >= len(self.lines):
                    raise YamlError(f"line {self.lineno(i)}: unterminated quoted string")
                piece = self.lines[j].strip()
                parts.append(piece if piece else "\n")
                closed = self._closes(" ".join(p for p in parts if p != "\n"), quote)
            joined = ""
            for part in parts:
                if part == "\n":
                    joined += "\n"
                elif joined and not joined.endswith("\n"):
                    joined += " " + part
                else:
                    joined += part
            return _scalar(_strip_comment(joined), self.lineno(i)), j + 1
        if text[:1] in "[{":
            return _scalar(text, self.lineno(i)), i + 1
        parts, j = [text], i + 1
        while j < len(self.lines):
            raw = self.lines[j]
            if raw.strip() and (_indent(raw) <= indent or raw.strip().startswith("#")):
                break
            if not raw.strip():
                k = self._skip(j)
                if k >= len(self.lines) or _indent(self.lines[k]) <= indent:
                    break
                parts.append("\n")
            else:
                piece = _strip_comment(raw.strip())
                if re.search(r":(?:\s|$)", piece):
                    raise YamlError(f"line {self.lineno(j)}: unexpected 'key: value' (check the indentation)")
                parts.append(piece)
            j += 1
        if len(parts) == 1:
            return _scalar(text, self.lineno(i)), i + 1
        joined = ""
        for part in parts:
            if part == "\n":
                joined += "\n"
            elif joined and not joined.endswith("\n"):
                joined += " " + part
            else:
                joined += part
        _scalar(joined.replace("\n", " "), self.lineno(i))  # same validity rules as one line
        return joined, j

    @staticmethod
    def _closes(text: str, quote: str) -> bool:
        body = text[1:]
        if quote == "'":
            body = body.replace("''", "")
            return "'" in body
        i = 0
        while i < len(body):
            if body[i] == "\\":
                i += 2
                continue
            if body[i] == '"':
                return True
            i += 1
        return False

    def _block_scalar(self, i: int, indent: int, m: "re.Match[str]") -> Tuple[str, int]:
        style = m.group(1)
        chomp = m.group(2) or m.group(4)
        explicit = int(m.group(3)) if m.group(3) else 0
        content: List[str] = []
        block_indent = indent + explicit if explicit else 0
        j = i
        while j < len(self.lines):
            raw = self.lines[j]
            if raw.strip():
                current = _indent(raw)
                if not block_indent:
                    if current <= indent:
                        break
                    block_indent = current
                if current < block_indent:
                    break
                content.append(raw[block_indent:])
            else:
                content.append("")
            j += 1
        trailing = 0
        while content and content[-1] == "":
            content.pop()
            trailing += 1
        if style == "|":
            body = "\n".join(content)
        else:
            pieces: List[str] = []
            for k, line in enumerate(content):
                if k == 0:
                    pieces.append(line)
                    continue
                prev = content[k - 1]
                if line == "":
                    pieces.append("\n")
                elif prev == "":
                    pieces.append(line)
                elif line.startswith(" ") or prev.startswith(" "):
                    pieces.append("\n" + line)
                else:
                    pieces.append(" " + line)
            body = "".join(pieces)
        if not content:
            return "", j
        if chomp == "-":
            return body, j
        if chomp == "+":
            return body + "\n" * (1 + trailing), j
        return body + "\n", j


def mini_yaml_load(text: str, first_line: int = 1) -> Any:
    return _MiniYaml(text, first_line).parse()


def yaml_load(text: str, first_line: int = 1, use_pyyaml: Optional[bool] = None) -> Any:
    """Parse YAML with PyYAML when available (``use_pyyaml`` forces a choice)."""
    if use_pyyaml is None:
        use_pyyaml = os.environ.get("RE_SKILLS_YAML", "auto") != "builtin"
    if use_pyyaml:
        try:
            import yaml  # type: ignore
        except ImportError:
            yaml = None
        if yaml is not None:
            try:
                return yaml.safe_load(text)
            except yaml.YAMLError as exc:
                mark = getattr(exc, "problem_mark", None)
                where = f"line {mark.line + first_line}: " if mark is not None else ""
                problem = getattr(exc, "problem", None) or str(exc).splitlines()[0]
                raise YamlError(f"{where}{problem}") from None
    return mini_yaml_load(text, first_line)


def split_frontmatter(text: str) -> Tuple[Optional[str], str, int]:
    """Return ``(frontmatter or None, body, body_first_line)``."""
    if text.startswith("\ufeff"):
        text = text[1:]
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0].strip() != "---":
        return None, text, 1
    for k in range(1, len(lines)):
        if lines[k].strip() in ("---", "..."):
            return "\n".join(lines[1:k]), "\n".join(lines[k + 1:]), k + 2
    return None, text, 1


# --------------------------------------------------------------------------- findings


@dataclass
class Finding:
    severity: str  # "error" | "warning"
    code: str
    message: str
    path: str = ""


@dataclass
class Skill:
    name: str  # folder name
    folder: Path
    stage_dir: str
    meta: Dict[str, Any] = field(default_factory=dict)
    frontmatter: Optional[Dict[str, Any]] = None
    findings: List[Finding] = field(default_factory=list)

    @property
    def declared_name(self) -> str:
        fm = self.frontmatter or {}
        return str(fm.get("name") or self.name)

    @property
    def expected_stage(self) -> str:
        return "primitives" if self.stage_dir == "_primitives" else self.stage_dir

    def error(self, code: str, message: str, path: str = "") -> None:
        self.findings.append(Finding("error", code, message, path))

    def warn(self, code: str, message: str, path: str = "") -> None:
        self.findings.append(Finding("warning", code, message, path))


def _rel(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return path.as_posix()


def _files(folder: Path) -> List[Path]:
    if not folder.is_dir():
        return []
    return sorted(p for p in folder.rglob("*")
                  if p.is_file() and not any(part.startswith(".") or part == "__pycache__"
                                             for part in p.relative_to(folder).parts))


def _split_names(value: Any) -> List[str]:
    if value is None:
        return []
    names = [n.strip() for n in str(value).split(",") if n.strip()]
    return [] if [n.lower() for n in names] == ["none"] else names


def planned_skills(root: Path) -> Dict[str, str]:
    """Skills listed in docs/epics.md (name -> planned invocation), for not-yet-written hand-offs."""
    epics = root / "docs" / "epics.md"
    planned: Dict[str, str] = {}
    if not epics.is_file():
        return planned
    text = epics.read_text(encoding="utf-8", errors="replace")
    for m in re.finditer(r"^\|\s*`([a-z0-9]+(?:-[a-z0-9]+)*)`\s*\((user|model|primitive)\b", text, re.M):
        planned.setdefault(m.group(1), m.group(2))
    for m in re.finditer(r"^\s*_primitives/\s+(.+)$", text, re.M):
        for name in m.group(1).split():
            if NAME_RE.match(name):
                planned.setdefault(name, "primitive")
    return planned


# --------------------------------------------------------------------------- per-skill checks


def discover(root: Path) -> List[Skill]:
    skills: List[Skill] = []
    base = root / "skills"
    if not base.is_dir():
        return skills
    for skill_md in sorted(base.glob("*/*/SKILL.md")):
        folder = skill_md.parent
        if folder.parent.name.startswith("."):
            continue
        skills.append(Skill(name=folder.name, folder=folder, stage_dir=folder.parent.name))
    return skills


def parse_skill(skill: Skill, root: Path) -> Optional[str]:
    """Load the frontmatter; return the body text (or None when SKILL.md is unusable)."""
    path = skill.folder / "SKILL.md"
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        skill.error("frontmatter", f"cannot read SKILL.md: {exc}")
        return None
    if not text.strip():
        skill.error("frontmatter", "SKILL.md is empty")
        return None
    raw, body, _ = split_frontmatter(text)
    if raw is None:
        skill.error("frontmatter", "SKILL.md must start with a '---' YAML frontmatter block closed by '---'")
        return text
    try:
        data = yaml_load(raw, first_line=2)
    except YamlError as exc:
        skill.error("frontmatter", f"invalid YAML: {exc}")
        return body
    if not isinstance(data, dict):
        skill.error("frontmatter", "frontmatter must be a mapping of keys to values")
        return body
    skill.frontmatter = data
    meta = data.get("metadata")
    skill.meta = meta if isinstance(meta, dict) else {}
    return body


def check_frontmatter(skill: Skill) -> None:
    fm = skill.frontmatter
    if fm is None:
        return
    for key in fm:
        if key not in ALLOWED_KEYS:
            skill.error("keys", f"frontmatter key {key!r} is not allowed (allowed: {', '.join(ALLOWED_KEYS)})")
    name = fm.get("name")
    if not isinstance(name, str) or not name:
        skill.error("name", "name is missing")
    else:
        if name != skill.name:
            skill.error("name", f"name {name!r} must equal the folder name {skill.name!r}")
        if not NAME_RE.match(name):
            skill.error("name", f"name {name!r} must be kebab-case (a-z, 0-9, single hyphens)")
        if len(name) > 64:
            skill.error("name", f"name is {len(name)} characters; the limit is 64")
    desc = fm.get("description")
    if not isinstance(desc, str) or not desc.strip():
        skill.error("description", "description is missing")
    else:
        if len(desc) > 1024:
            skill.error("description", f"description is {len(desc)} characters; the limit is 1024")
        if "Use when" not in desc:
            near = re.search(r"\bUse\b[^.;]{0,80}?\bwhen\b", desc, re.I)
            found = f' (found "{near.group(0)}"; start the trigger sentence with "Use when")' if near else ""
            skill.error("description", f'description must say "Use when ..." (the triggers){found}')
        if "Not for" not in desc:
            near = re.search(r"\bNot\s+(?:a|an|the|to|meant|intended)\b[^.;]{0,30}", desc, re.I)
            found = f' (found "{near.group(0)}"; write "Not for ...")' if near else ""
            skill.error("description", 'description must say "Not for ..." (the nearest neighbour to use '
                                       f'instead){found}')
    if fm.get("license") != "MIT":
        skill.error("license", f"license must be MIT (got {fm.get('license')!r})")
    if "compatibility" in fm:
        if not isinstance(fm["compatibility"], str) or not fm["compatibility"].strip():
            skill.error("compatibility", "compatibility must be a non-empty string")
        elif not (skill.folder / "scripts").is_dir():
            skill.warn("compatibility", "compatibility is set but the skill has no scripts/ folder")
    for key in ("disable-model-invocation", "user-invocable"):
        if key in fm and not isinstance(fm[key], bool):
            skill.error("invocation", f"{key} must be true or false (got {fm[key]!r})")
    if "argument-hint" in fm and not isinstance(fm["argument-hint"], str):
        skill.error("keys", "argument-hint must be a string")

    meta = fm.get("metadata")
    if not isinstance(meta, dict):
        skill.error("metadata", "metadata must be a mapping with " + ", ".join(METADATA_KEYS))
        return
    for key in METADATA_KEYS:
        if key not in meta:
            skill.error("metadata", f"metadata.{key} is missing")
    for key, value in meta.items():
        if key not in METADATA_KEYS:
            skill.error("metadata", f"metadata key {key!r} is not allowed (allowed: {', '.join(METADATA_KEYS)})")
        elif not isinstance(value, str):
            skill.error("metadata", f"metadata.{key} must be a string; quote it (got {value!r})")
        elif not value.strip():
            skill.error("metadata", f"metadata.{key} is empty")
    stage = meta.get("stage")
    if isinstance(stage, str) and stage:
        if stage not in STAGES + ("primitives",):
            skill.error("stage", f"metadata.stage {stage!r} is not a stage ({', '.join(STAGES + ('primitives',))})")
        elif stage != skill.expected_stage:
            skill.error("stage", f"metadata.stage {stage!r} does not match the folder skills/{skill.stage_dir}/")
    elif skill.stage_dir not in STAGES and skill.stage_dir != "_primitives":
        skill.error("stage", f"skills/{skill.stage_dir}/ is not a stage directory")
    invocation = meta.get("invocation")
    if isinstance(invocation, str) and invocation:
        if invocation not in INVOCATIONS:
            skill.error("invocation", f"metadata.invocation {invocation!r} must be one of {', '.join(INVOCATIONS)}")
        else:
            check_invocation(skill, invocation, fm)
    priority = meta.get("priority")
    if isinstance(priority, str) and priority and priority not in PRIORITIES:
        skill.error("metadata", f"metadata.priority {priority!r} must be one of {', '.join(PRIORITIES)}")
    version = meta.get("version")
    if isinstance(version, str) and version and not VERSION_RE.match(version):
        skill.error("metadata", f"metadata.version {version!r} must be a semantic version such as \"0.1.0\"")
    anchor = meta.get("ireb-anchor")
    if isinstance(anchor, str) and anchor and "Handbook" not in anchor:
        skill.warn("ireb-anchor", "metadata.ireb-anchor should cite the CPRE FL Handbook 1.2 section(s)")


def check_invocation(skill: Skill, invocation: str, fm: Dict[str, Any]) -> None:
    disable = fm.get("disable-model-invocation")
    user_invocable = fm.get("user-invocable")
    if invocation == "user":
        if disable is not True:
            skill.error("invocation", "user-invoked skills must set disable-model-invocation: true")
        if user_invocable is False:
            skill.error("invocation", "user-invoked skills must not set user-invocable: false")
    elif invocation == "primitive":
        if user_invocable is not False:
            skill.error("invocation", "primitives must set user-invocable: false")
        if disable is True:
            skill.error("invocation", "primitives must not set disable-model-invocation: true (other skills load them)")
    else:
        if disable is True:
            skill.error("invocation", "model-invoked skills must not set disable-model-invocation: true")
        if user_invocable is False:
            skill.error("invocation", "model-invoked skills must not set user-invocable: false")
    if "argument-hint" in fm and invocation != "user":
        skill.warn("keys", "argument-hint is for user-invoked skills only")
    if invocation == "primitive" and skill.stage_dir != "_primitives":
        skill.error("invocation", "primitives live in skills/_primitives/")
    if skill.stage_dir == "_primitives" and invocation != "primitive":
        skill.error("invocation", "skills in skills/_primitives/ must have invocation: primitive")


def headings(body: str) -> List[Tuple[int, str]]:
    out: List[Tuple[int, str]] = []
    fence = None
    for line in body.split("\n"):
        stripped = line.strip()
        marker = re.match(r"^(`{3,}|~{3,})", stripped)
        if marker:
            if fence is None:
                fence = marker.group(1)[0]
            elif stripped.startswith(fence * 3):
                fence = None
            continue
        if fence:
            continue
        m = re.match(r"^(#{1,6})\s+(.+?)\s*#*\s*$", line)
        if m:
            out.append((len(m.group(1)), m.group(2).strip()))
    return out


def check_body(skill: Skill, text_lines: int, body: str) -> None:
    invocation = skill.meta.get("invocation") if isinstance(skill.meta.get("invocation"), str) else None
    if invocation in LINE_BUDGET:
        budget = LINE_BUDGET[invocation]
        if text_lines >= budget:
            skill.error("line-budget", f"SKILL.md has {text_lines} lines; {invocation}-invoked skills must stay under {budget}")
        elif invocation == "user" and text_lines >= USER_TARGET:
            skill.warn("line-budget", f"SKILL.md has {text_lines} lines; aim for under {USER_TARGET}")
    found = headings(body)
    if not any(level == 1 for level, _ in found):
        skill.warn("headings", "SKILL.md has no '# <Human title>' heading")
    h2 = [title for level, title in found if level == 2]
    positions = []
    for title in REQUIRED_HEADINGS:
        if title not in h2:
            skill.error("headings", f"missing section '## {title}'")
        else:
            positions.append((h2.index(title), title))
    if [t for _, t in sorted(positions)] != [t for _, t in positions]:
        order = ", ".join(t for _, t in sorted(positions))
        skill.error("headings", f"sections out of order ({order}); required order: {', '.join(REQUIRED_HEADINGS)}")
    if "Hand-offs" in h2:
        last = h2.index("Hand-offs")
        for title in h2[:last]:
            if title in OPTIONAL_HEADINGS:
                skill.warn("headings", f"optional section '## {title}' should come after '## Hand-offs'")


def check_anchor(skill: Skill, root: Path) -> None:
    anchor = skill.folder / "references" / "ireb-anchor.md"
    if not anchor.is_file():
        skill.error("ireb-anchor", "references/ireb-anchor.md is missing")
        return
    text = anchor.read_text(encoding="utf-8", errors="replace")
    if "independent of IREB" not in text:
        skill.error("ireb-anchor", 'references/ireb-anchor.md must state that re-skills is "independent of IREB"')


def check_folders(skill: Skill, root: Path) -> None:
    primitive = skill.meta.get("invocation") == "primitive" or skill.stage_dir == "_primitives"
    if not primitive:
        if not _files(skill.folder / "assets"):
            skill.error("assets", "assets/ is missing or empty (the fixed output shape)")
        examples = _files(skill.folder / "examples")
        if len(examples) < 2:
            skill.error("examples", f"examples/ needs an input and its expected output (found {len(examples)} file(s))")
    evals = skill.folder / "evals"
    cases = sorted(p for p in evals.iterdir() if p.is_dir() and not p.name.startswith(".")) if evals.is_dir() else []
    if not primitive or cases:
        if len(cases) < 3:
            skill.error("evals", f"evals/ needs at least 3 case folders (found {len(cases)})")
        if not any(c.name.startswith("adversarial-") for c in cases):
            skill.error("evals", "evals/ needs a case folder starting with 'adversarial-'")
    for case in cases:
        check_case(skill, case, root)


def _front(path: Path) -> Tuple[Optional[Dict[str, Any]], str, Optional[str]]:
    """``(settings mapping or None, body, error)`` for a Markdown file with a frontmatter block."""
    text = path.read_text(encoding="utf-8", errors="replace")
    raw, body, _ = split_frontmatter(text)
    if raw is None:
        return None, text, "has no '---' settings block"
    try:
        data = yaml_load(raw, first_line=2)
    except YamlError as exc:
        return None, body, f"settings block is not valid YAML: {exc}"
    if data is None:
        data = {}
    if not isinstance(data, dict):
        return None, body, "settings block must be a mapping"
    return data, body, None


def check_case(skill: Skill, case: Path, root: Path) -> None:
    where = f"evals/{case.name}"
    prompt = case / "prompt.md"
    if not prompt.is_file():
        skill.error("eval-case", f"{where}: prompt.md is missing")
    else:
        settings, body, problem = _front(prompt)
        if problem:
            skill.error("eval-case", f"{where}/prompt.md {problem}")
        else:
            extra = [k for k in settings or {} if k not in PROMPT_SETTINGS]
            if extra:
                skill.error("eval-case", f"{where}/prompt.md: settings keys {', '.join(map(repr, extra))} "
                                         f"not allowed (allowed: {', '.join(PROMPT_SETTINGS)})")
        if not body.strip():
            skill.error("eval-case", f"{where}/prompt.md has no prompt after the settings block")
    case_yaml = case / "case.yaml"
    data: Dict[str, Any] = {}
    if not case_yaml.is_file():
        skill.error("eval-case", f"{where}: case.yaml is missing")
    else:
        try:
            loaded = yaml_load(case_yaml.read_text(encoding="utf-8", errors="replace"))
        except YamlError as exc:
            skill.error("eval-case", f"{where}/case.yaml is not valid YAML: {exc}")
            loaded = None
        if loaded is not None and not isinstance(loaded, dict):
            skill.error("eval-case", f"{where}/case.yaml must be a mapping")
        elif isinstance(loaded, dict):
            data = loaded
            version = data.get("schema_version")
            if version != "1.1":
                hint = " (quote it: \"1.1\")" if version == 1.1 else ""
                skill.error("eval-case", f"{where}/case.yaml: schema_version must be \"1.1\" (got {version!r}){hint}")
            if data.get("name") != case.name:
                skill.error("eval-case", f"{where}/case.yaml: name must equal the folder name {case.name!r} "
                                         f"(got {data.get('name')!r})")
            outcome = data.get("expected_outcome")
            if not isinstance(outcome, str) or not outcome.strip():
                skill.error("eval-case", f"{where}/case.yaml: expected_outcome is missing")
    graders = sorted((case / "graders").glob("*.md")) if (case / "graders").is_dir() else []
    if not graders:
        skill.error("grader", f"{where}: graders/ needs at least one NN-<few-words>.md file")
    for grader in graders:
        settings, body, problem = _front(grader)
        label = f"{where}/graders/{grader.name}"
        if problem:
            skill.error("grader", f"{label} {problem}")
            continue
        missing = [k for k in GRADER_KEYS if k not in (settings or {})]
        if missing:
            skill.error("grader", f"{label}: settings block is missing {', '.join(missing)}")
        weight = (settings or {}).get("weight")
        if "weight" not in missing and (isinstance(weight, bool) or not isinstance(weight, (int, float))):
            skill.error("grader", f"{label}: weight must be a number (got {weight!r})")
        if not body.strip():
            skill.error("grader", f"{label} has no statement after the settings block")
    if (case / "files").is_dir():
        script = case / "place-files.sh"
        if not script.is_file():
            skill.error("eval-case", f"{where}: files/ exists but place-files.sh is missing")
        elif os.name == "posix" and not os.access(script, os.X_OK):
            skill.warn("eval-case", f"{where}/place-files.sh is not executable (chmod +x)")
        context = data.get("context") if isinstance(data.get("context"), dict) else {}
        scaffold = context.get("scaffold_script") if context else None
        if not scaffold:
            skill.error("eval-case", f"{where}/case.yaml: files/ exists, so context.scaffold_script must name place-files.sh")
        elif not (case / str(scaffold)).is_file():
            skill.error("eval-case", f"{where}/case.yaml: context.scaffold_script {scaffold!r} does not exist")


def check_handoffs(skills: Sequence[Skill], planned: Dict[str, str], strict: bool) -> None:
    present = {s.declared_name for s in skills} | {s.name for s in skills}
    for skill in skills:
        for key in ("inputs-from", "outputs-to"):
            value = skill.meta.get(key)
            if not isinstance(value, str):
                continue
            for name in _split_names(value):
                if name in present:
                    continue
                if name == skill.name:
                    continue
                if name in planned and not strict:
                    skill.warn("handoff", f"metadata.{key} names {name!r}, which is planned (docs/epics.md) "
                                          "but not in the catalogue yet")
                else:
                    skill.error("handoff", f"metadata.{key} names {name!r}, which is not a skill in the catalogue")


def check_unique(skills: Sequence[Skill], root: Path) -> None:
    seen: Dict[str, Skill] = {}
    for skill in skills:
        key = skill.declared_name
        if key in seen:
            other = seen[key]
            skill.error("duplicate-name", f"name {key!r} is also used by {_rel(other.folder, root)}")
        else:
            seen[key] = skill


def validate(root: Path, only: Optional[str] = None, strict_handoffs: bool = False) -> List[Skill]:
    skills = discover(root)
    for skill in skills:
        try:
            body = parse_skill(skill, root)
            if body is None:
                continue
            text = (skill.folder / "SKILL.md").read_text(encoding="utf-8")
            check_frontmatter(skill)
            check_body(skill, len(text.rstrip("\n").split("\n")), body)
            check_anchor(skill, root)
            check_folders(skill, root)
        except Exception as exc:  # a half-written skill must never crash the whole run
            skill.error("internal", f"validator could not finish this skill: {type(exc).__name__}: {exc}")
    check_handoffs(skills, planned_skills(root), strict_handoffs)
    check_unique(skills, root)
    if only:
        skills = [s for s in skills if s.name == only or s.declared_name == only]
    return skills


# --------------------------------------------------------------------------- report


def report_text(skills: Sequence[Skill], root: Path, quiet: bool = False) -> str:
    out: List[str] = []
    for skill in skills:
        rel = _rel(skill.folder, root)
        errors = [f for f in skill.findings if f.severity == "error"]
        warnings = [f for f in skill.findings if f.severity == "warning"]
        if not skill.findings:
            if not quiet:
                out.append(f"ok    {rel}")
            continue
        status = "FAIL" if errors else "warn"
        out.append(f"{status:<5} {rel} ({len(errors)} error(s), {len(warnings)} warning(s))")
        for f in errors + warnings:
            out.append(f"        {f.severity:<7} {f.code}: {f.message}")
    totals = _totals(skills)
    by_code = ", ".join(f"{code} {n}" for code, n in sorted(totals["error_codes"].items()))
    out.append("")
    out.append(f"{len(skills)} skill(s) checked: {totals['ok']} ok, {totals['failed']} with errors; "
               f"{totals['errors']} error(s), {totals['warnings']} warning(s)")
    if by_code:
        out.append(f"errors by type: {by_code}")
    return "\n".join(out) + "\n"


def _totals(skills: Sequence[Skill]) -> Dict[str, Any]:
    codes: Dict[str, int] = {}
    errors = warnings = failed = ok = 0
    for skill in skills:
        e = [f for f in skill.findings if f.severity == "error"]
        errors += len(e)
        warnings += sum(1 for f in skill.findings if f.severity == "warning")
        failed += 1 if e else 0
        ok += 0 if skill.findings else 1
        for f in e:
            codes[f.code] = codes.get(f.code, 0) + 1
    return {"errors": errors, "warnings": warnings, "failed": failed, "ok": ok, "error_codes": codes}


def report_json(skills: Sequence[Skill], root: Path) -> str:
    doc = {
        "skills": [{"name": s.name, "path": _rel(s.folder, root),
                    "findings": [{"severity": f.severity, "code": f.code, "message": f.message}
                                 for f in s.findings]} for s in skills],
        "summary": _totals(skills),
    }
    return json.dumps(doc, indent=2) + "\n"


# --------------------------------------------------------------------------- generated docs


_ABBREVIATIONS = ("e.g.", "i.e.", "etc.", "vs.", "cf.", "approx.")


def _first_sentence(text: str) -> str:
    flat = re.sub(r"\s+", " ", text or "").strip()
    for m in re.finditer(r"(?<=[.!?])\s+(?=[A-Z`\"(])", flat):
        before = flat[: m.start()]
        if not before.lower().endswith(_ABBREVIATIONS):
            return before
    return flat


def _md_cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _stage_key(skill: Skill) -> Tuple[int, str]:
    stage = skill.meta.get("stage") if isinstance(skill.meta.get("stage"), str) else skill.expected_stage
    order = list(STAGES) + ["primitives"]
    return (order.index(stage) if stage in order else len(order), skill.name)


def catalogue_markdown(skills: Sequence[Skill], root: Path) -> str:
    usable = sorted((s for s in skills if s.frontmatter is not None), key=_stage_key)
    out = [
        GENERATED_NOTE,
        "",
        "# Skill catalogue",
        "",
        "Every skill in `skills/`, generated from the `SKILL.md` frontmatter. Invocation: **user** "
        "skills are started by a person (`/name`), **model** skills are picked by the agent from "
        "their description, **primitives** are used by other skills.",
        "",
        "| Stage | Skill | Invocation | Priority | What it does | Work product | IREB anchor |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for s in usable:
        meta = s.meta
        stage = meta.get("stage") or s.expected_stage
        link = f"[`{s.declared_name}`](../{_rel(s.folder, root)}/SKILL.md)"
        work = meta.get("work-product") or ""
        out.append("| " + " | ".join([
            _md_cell(STAGE_TITLES.get(str(stage), str(stage))), link, _md_cell(meta.get("invocation") or ""),
            _md_cell(meta.get("priority") or ""), _md_cell(_first_sentence(str((s.frontmatter or {}).get("description") or ""))),
            _md_cell(f"`{work}`" if work and "/" in str(work) and " " not in str(work) else work),
            _md_cell(meta.get("ireb-anchor") or ""),
        ]) + " |")
    counts: Dict[str, int] = {}
    for s in usable:
        counts[str(s.meta.get("invocation") or "?")] = counts.get(str(s.meta.get("invocation") or "?"), 0) + 1
    summary = ", ".join(f"{n} {k}" for k, n in sorted(counts.items()))
    out += ["", f"{len(usable)} skills ({summary}). Hand-offs between them: [pipeline.md](pipeline.md).", ""]
    return "\n".join(out)


def _node(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def pipeline_markdown(skills: Sequence[Skill], root: Path) -> str:
    usable = sorted((s for s in skills if s.frontmatter is not None), key=_stage_key)
    names = {s.declared_name for s in usable}
    edges = set()
    for s in usable:
        for target in _split_names(s.meta.get("outputs-to")):
            if target in names and target != s.declared_name:
                edges.add((s.declared_name, target))
        for source in _split_names(s.meta.get("inputs-from")):
            if source in names and source != s.declared_name:
                edges.add((source, s.declared_name))
    out = [
        GENERATED_NOTE,
        "",
        "# Hand-off pipeline",
        "",
        "Which skill's work product feeds which, generated from `metadata.outputs-to` and "
        "`metadata.inputs-from` in each `SKILL.md`. Skills are grouped by stage.",
        "",
        "```mermaid",
        "flowchart LR",
    ]
    by_stage: Dict[str, List[Skill]] = {}
    for s in usable:
        stage = str(s.meta.get("stage") or s.expected_stage)
        by_stage.setdefault(stage, []).append(s)
    for stage in list(STAGES) + ["primitives"] + sorted(k for k in by_stage if k not in STAGES and k != "primitives"):
        members = by_stage.get(stage)
        if not members:
            continue
        out.append(f'  subgraph {_node("stage_" + stage)}["{STAGE_TITLES.get(stage, stage)}"]')
        for s in members:
            shape = f'(["{s.declared_name}"])' if s.meta.get("invocation") == "user" else f'["{s.declared_name}"]'
            out.append(f"    {_node(s.declared_name)}{shape}")
        out.append("  end")
    for a, b in sorted(edges):
        out.append(f"  {_node(a)} --> {_node(b)}")
    out += [
        "```",
        "",
        "Rounded nodes are user-invoked skills; square nodes are model-invoked skills and primitives.",
        "",
        f"{len(usable)} skills, {len(edges)} hand-offs.",
        "",
    ]
    return "\n".join(out)


def generated_docs(skills: Sequence[Skill], root: Path) -> Dict[Path, str]:
    return {
        root / "docs" / "catalogue.md": catalogue_markdown(skills, root),
        root / "docs" / "pipeline.md": pipeline_markdown(skills, root),
    }


# --------------------------------------------------------------------------- main


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Validate every skill against docs/authoring-guide.md.",
        epilog="Exit codes: 0 ok, 1 errors (or stale docs with --check-docs), 2 usage error.")
    parser.add_argument("--warn-only", action="store_true", help="report problems but always exit 0")
    parser.add_argument("--skill", metavar="NAME", help="validate one skill")
    parser.add_argument("--strict-handoffs", action="store_true",
                        help="treat hand-offs to planned but missing skills as errors")
    parser.add_argument("--write-docs", action="store_true", help="write docs/catalogue.md and docs/pipeline.md")
    parser.add_argument("--check-docs", action="store_true", help="exit 1 if docs/catalogue.md or docs/pipeline.md is stale")
    parser.add_argument("--format", choices=("text", "json"), default="text", help="report format")
    parser.add_argument("-q", "--quiet", action="store_true", help="list only skills with problems")
    parser.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    if not (root / "skills").is_dir():
        sys.stderr.write(f"validate_catalogue: error: {root / 'skills'} not found\n")
        return 2
    skills = validate(root, strict_handoffs=args.strict_handoffs)
    if args.write_docs or args.check_docs:
        stale = []
        for path, content in generated_docs(skills, root).items():
            current = path.read_text(encoding="utf-8") if path.is_file() else None
            if current == content:
                continue
            if args.write_docs:
                path.parent.mkdir(parents=True, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as handle:
                    handle.write(content)
                print(f"wrote {_rel(path, root)}")
            else:
                stale.append(_rel(path, root))
        if stale:
            print(f"stale generated docs: {', '.join(stale)}; run `python3 tools/validate_catalogue.py --write-docs`")
            return 1
        if args.check_docs:
            print("generated docs are up to date")
        return 0
    if args.skill:
        selected = [s for s in skills if s.name == args.skill or s.declared_name == args.skill]
        if not selected:
            sys.stderr.write(f"validate_catalogue: error: no skill named {args.skill!r}\n")
            return 2
        skills = selected
    if args.format == "json":
        sys.stdout.write(report_json(skills, root))
    else:
        sys.stdout.write(report_text(skills, root, quiet=args.quiet))
    has_errors = any(f.severity == "error" for s in skills for f in s.findings)
    return 0 if args.warn_only or not has_errors else 1


if __name__ == "__main__":
    sys.exit(main())
