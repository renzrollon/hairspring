#!/usr/bin/env python3
"""Vendor the re-lint modules into the skills that bundle them, and generate rules.md.

A skill installed on its own must still run its scripts, so each skill that needs a ``re-lint``
command carries a copy of the module in its ``scripts/`` folder (with ``reqio.py`` next to it).
This tool makes those copies from ``packages/re-lint/src/re_lint/`` following the vendoring map in
``docs/tooling-contract.md``, and writes
``skills/validation/requirement-linter/references/rules.md`` from the rule registry in ``lint.py``.

Usage:
  python3 tools/vendor_scripts.py            # write or refresh every copy
  python3 tools/vendor_scripts.py --check    # exit 1 and list drift; writes nothing (CI)
  python3 tools/vendor_scripts.py --strict   # also fail on missing source modules or target skills

A missing source module or target skill is a warning (the catalogue is still being written)
unless ``--strict`` is given. Exit codes: 0 ok, 1 drift or strict failure, 2 usage error.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import os
import stat
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

ROOT = Path(__file__).resolve().parent.parent
PACKAGE_DIR = Path("packages/re-lint/src/re_lint")
SCHEMA_SOURCE = Path("skills/_primitives/re-templates/assets/schema.json")
RULES_DOC_SKILL = "requirement-linter"
RULES_DOC = Path("references/rules.md")

# package module -> (vendored file name, skills that carry it)
VENDOR_MAP: Tuple[Tuple[str, str, Tuple[str, ...]], ...] = (
    ("lint.py", "lint_requirements.py", ("requirement-linter", "requirement-phrasing", "requirements-review")),
    ("ids.py", "re_ids.py", ("re-ids",)),
    ("tracing.py", "trace_matrix.py", ("traceability-matrix", "change-impact")),
    ("baseline.py", "baseline.py", ("baseline",)),
    ("views.py", "views.py", ("attribute-schema",)),
    ("prioritize.py", "prioritize.py", ("prioritization",)),
    ("reqif_io.py", "reqif_bridge.py", ("reqif-bridge",)),
    ("openspec.py", "to_openspec.py", ("to-openspec",)),
    ("issues.py", "issue_sync.py", ("issue-sync",)),
)
SCHEMA_TARGETS = ("re-setup", "attribute-schema")
MARKER = "VENDORED from packages/re-lint/src/re_lint/"


def header(module: str) -> str:
    return (f"# {MARKER}{module} by tools/vendor_scripts.py; do not edit.\n"
            "# Change the package module, then run `python3 tools/vendor_scripts.py` to refresh this copy.\n")


def vendored_text(source: str, module: str) -> str:
    """``source`` with the shebang first and the two-line VENDORED header right after it."""
    text = source.replace("\r\n", "\n")
    if text.startswith("#!"):
        shebang, _, rest = text.partition("\n")
    else:
        shebang, rest = "#!/usr/bin/env python3", text
    return f"{shebang}\n{header(module)}{rest}"


class Plan:
    """Every file the tool owns, with the content it should have."""

    def __init__(self) -> None:
        self.files: Dict[Path, Tuple[str, bool]] = {}  # path -> (content, executable)
        self.warnings: List[str] = []
        self.owned_dirs: List[Path] = []  # scripts/ folders whose VENDORED files we manage

    def add(self, path: Path, content: str, executable: bool) -> None:
        self.files[path] = (content, executable)


def find_skills(root: Path) -> Dict[str, Path]:
    skills: Dict[str, Path] = {}
    base = root / "skills"
    if not base.is_dir():
        return skills
    # A folder counts even before its SKILL.md is written, so scripts land in half-written skills.
    for folder in sorted(base.glob("*/*/")):
        if folder.is_dir() and not folder.name.startswith((".", "_")) and not folder.parent.name.startswith("."):
            skills.setdefault(folder.name, folder)
    return skills


def load_lint_module(root: Path):
    """Import ``lint.py`` from the package source tree the way a vendored copy runs (standalone)."""
    path = root / PACKAGE_DIR / "lint.py"
    if not path.is_file():
        return None
    name = "_vendored_lint_" + hashlib.sha1(str(path).encode("utf-8")).hexdigest()[:12]
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    sys.modules[name] = module  # dataclasses look the module up while the class is created
    try:
        spec.loader.exec_module(module)  # type: ignore[union-attr]
    except BaseException:
        sys.modules.pop(name, None)
        raise
    return module


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def rules_markdown(lint) -> str:
    """The generated ``references/rules.md`` for the requirement-linter skill."""
    rules = list(lint.RULES.values())
    text_rules = [r.id for r in rules if r.kind == "text"]
    out = [
        "<!-- GENERATED by tools/vendor_scripts.py from packages/re-lint/src/re_lint/lint.py (RULES); do not edit. -->",
        "",
        "# re-lint rules",
        "",
        "The rules `re-lint check` (and `scripts/lint_requirements.py`) apply to every requirement row. "
        "Rule IDs are stable. When Python is not available, apply this table by hand: read each "
        "requirement's `Text` and attributes, and report findings in the same shape "
        "(`<file>:<line>: <severity> <rule> <ID>: <message>`).",
        "",
        "| Rule | Default | Detects | Example that fires | Fix hint |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rules:
        out.append(f"| `{r.id}` | {r.severity} | {_cell(r.summary)} | {_cell(r.example)} | {_cell(r.hint)} |")
    out += [
        "",
        "## How the rules apply",
        "",
        f"- Text rules ({', '.join(f'`{r}`' for r in text_rules)}) run on `Text`; `open-tbd` also "
        "checks every attribute.",
        "- Story-form requirements (`As a ..., I want ...`) skip `missing-obligation`, `future-tense` "
        "and `passive-voice`.",
        "- Rows with status `withdrawn` or `rejected` only get the structural rules.",
        "- `requirements.csv` is the register. A Markdown table is a register only when its header has "
        "every required attribute; other tables are views: rows that echo the register are checked "
        "for drift, and rows with an unregistered ID get the text rules only.",
        "- `TBD` is a valid placeholder in any attribute: `open-tbd` reports it (info), never "
        "`missing-attribute` or `invalid-enum`. Run `--fail-on info` on a release branch to block on "
        "open TBDs.",
        "- Quoted (`\"...\"`) and backticked spans are not linted as prose.",
        "- In EARS sentences, `universal-quantifier`, `passive-voice` and `compound-requirement` look "
        "at the response clause (after the condition), so states such as `WHILE the account is "
        "locked` are not reported.",
        "- `passive-voice` ignores passives with a `by <actor>` phrase, relative clauses (`points that "
        "were earned`), subordinate conditions (`when the purchase is completed`) and placeholders "
        "(`to be confirmed`).",
        "- `IF` written in capitals is the EARS unwanted-behavior keyword and needs `THEN`.",
        "- `any` is reported only where it means \"every\" (`for any`, `at any time`, `shall accept "
        "any`, `Any member ...`), not in conditions (`IF any payment fails`).",
        "- `every` followed by an interval (`every 24 hours`, `every day`) is a frequency, not a "
        "universal claim.",
        "",
        "## Word lists",
        "",
        "Weak words (`weak-word`):",
        "",
        ", ".join(f"`{w}`" for w in lint.WEAK_WORDS),
        "",
        "Universal quantifiers (`universal-quantifier`), plus `any` where it means \"every\":",
        "",
        ", ".join(f"`{w}`" for w in lint.UNIVERSAL_WORDS),
        "",
        "Nominalizations (`nominalization`), reported as `<word> of`, plus `processing`:",
        "",
        ", ".join(f"`{w}`" for w in lint.NOMINALIZATIONS),
        "",
        "## Configuration",
        "",
        "In `requirements/schema.json`:",
        "",
        "```json",
        '"lint": {',
        '  "disable": ["nominalization"],',
        '  "severity": {"passive-voice": "error", "open-tbd": "off"},',
        '  "extra_weak_words": ["blazing"],',
        '  "allow_words": ["Flexible Spending Account"]',
        "}",
        "```",
        "",
        "- `disable`: rules that never run.",
        "- `severity`: per-rule `error`, `warning`, `info` or `off`.",
        "- `extra_weak_words`: more words or phrases for `weak-word`.",
        "- `allow_words`: words or phrases (such as glossary terms) never reported by `weak-word`, "
        "`universal-quantifier` or `nominalization`.",
        "",
        "On the command line: `--disable RULE[,RULE]`, `--enable RULE[,RULE]` (overrides "
        "`lint.disable`), `--fail-on error|warning|info`, `--only-ids R-001,R-002`, "
        "`--changed-only origin/main`, `--format text|json|github|sarif`.",
        "",
        "Exit codes: `0` clean, `1` findings at or above `--fail-on`, `2` usage, schema or parse error.",
        "",
    ]
    return "\n".join(out)


def build_plan(root: Path) -> Plan:
    plan = Plan()
    skills = find_skills(root)
    pkg = root / PACKAGE_DIR
    reqio_path = pkg / "reqio.py"
    reqio_text = vendored_text(reqio_path.read_text(encoding="utf-8"), "reqio.py") if reqio_path.is_file() else None
    if reqio_text is None:
        plan.warnings.append(f"source module {PACKAGE_DIR / 'reqio.py'} not found; nothing vendored")
        return plan
    for module, target, skill_names in VENDOR_MAP:
        source = pkg / module
        present = [n for n in skill_names if n in skills]
        for name in skill_names:
            if name in skills:
                plan.owned_dirs.append(skills[name] / "scripts")
            else:
                plan.warnings.append(f"target skill {name!r} not found; {target} not vendored into it")
        if not source.is_file():
            plan.warnings.append(f"source module {PACKAGE_DIR / module} not found; skipped "
                                 f"({target} for {', '.join(skill_names)})")
            continue
        text = vendored_text(source.read_text(encoding="utf-8"), module)
        for name in present:
            scripts = skills[name] / "scripts"
            plan.add(scripts / target, text, True)
            plan.add(scripts / "reqio.py", reqio_text, True)
    schema = root / SCHEMA_SOURCE
    if schema.is_file():
        schema_text = schema.read_text(encoding="utf-8")
        for name in SCHEMA_TARGETS:
            if name in skills:
                plan.add(skills[name] / "assets" / "schema.json", schema_text, False)
            else:
                plan.warnings.append(f"target skill {name!r} not found; schema.json not copied into it")
    else:
        plan.warnings.append(f"{SCHEMA_SOURCE} not found; schema.json not copied")
    if RULES_DOC_SKILL in skills:
        try:
            lint = load_lint_module(root)
        except Exception as exc:  # a broken lint.py must be reported, not crash the tool
            plan.warnings.append(f"could not import lint.py to generate rules.md: {type(exc).__name__}: {exc}")
            lint = None
        if lint is not None:
            plan.add(skills[RULES_DOC_SKILL] / RULES_DOC, rules_markdown(lint), False)
        elif not (pkg / "lint.py").is_file():
            plan.warnings.append("lint.py not found; rules.md not generated")
    else:
        plan.warnings.append(f"target skill {RULES_DOC_SKILL!r} not found; rules.md not generated")
    return plan


def _is_vendored(path: Path) -> bool:
    try:
        with open(path, encoding="utf-8") as handle:
            head = handle.read(400)
    except (OSError, UnicodeDecodeError):
        return False
    return MARKER in head and "tools/vendor_scripts.py" in head


def orphans(plan: Plan) -> List[Path]:
    """Vendored files that the map no longer produces (renamed or dropped modules)."""
    out = []
    for folder in plan.owned_dirs:
        if folder.is_dir():
            for path in sorted(folder.glob("*.py")):
                if path not in plan.files and _is_vendored(path):
                    out.append(path)
    return out


def _executable(path: Path) -> bool:
    return bool(path.stat().st_mode & stat.S_IXUSR)


def drift(plan: Plan) -> List[str]:
    problems = []
    for path, (content, executable) in sorted(plan.files.items()):
        if not path.is_file():
            problems.append(f"missing: {path}")
            continue
        if path.read_text(encoding="utf-8") != content:
            problems.append(f"stale: {path}")
        elif executable and os.name == "posix" and not _executable(path):
            problems.append(f"not executable: {path}")
    problems += [f"orphaned vendored copy: {p}" for p in orphans(plan)]
    return problems


def write(plan: Plan) -> List[str]:
    changed = []
    for path, (content, executable) in sorted(plan.files.items()):
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            changed.append(f"wrote: {path}")
        if executable and os.name == "posix":
            mode = path.stat().st_mode
            if not mode & stat.S_IXUSR:
                path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
                changed.append(f"chmod +x: {path}")
    for path in orphans(plan):
        path.unlink()
        changed.append(f"removed orphan: {path}")
    return changed


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                     epilog="Exit codes: 0 ok, 1 drift or strict failure, 2 usage error.")
    parser.add_argument("--check", action="store_true", help="report drift and exit 1; write nothing")
    parser.add_argument("--strict", action="store_true",
                        help="fail when a source module or target skill is missing")
    parser.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    parser.add_argument("-q", "--quiet", action="store_true", help="print problems only")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    if not (root / PACKAGE_DIR).is_dir():
        sys.stderr.write(f"vendor_scripts: error: {root / PACKAGE_DIR} not found\n")
        return 2
    plan = build_plan(root)

    def rel(text: str) -> str:
        return text.replace(str(root) + os.sep, "")

    for warning in plan.warnings:
        sys.stderr.write(f"vendor_scripts: {'error' if args.strict else 'warning'}: {rel(warning)}\n")
    status = 1 if (args.strict and plan.warnings) else 0
    if args.check:
        problems = drift(plan)
        for problem in problems:
            print(rel(problem))
        if problems:
            print(f"vendor_scripts: {len(problems)} vendored file(s) out of date; "
                  "run `python3 tools/vendor_scripts.py` and commit the result")
            return 1
        if not args.quiet:
            print(f"vendor_scripts: {len(plan.files)} vendored file(s) up to date")
        return status
    changed = write(plan)
    if not args.quiet:
        for line in changed:
            print(rel(line))
        print(f"vendor_scripts: {len(plan.files)} file(s) in sync ({len(changed)} change(s))")
    return status


if __name__ == "__main__":
    sys.exit(main())
