#!/usr/bin/env python3
"""Generate agent-specific sidecar files from each skill's SKILL.md.

Today this writes ``agents/openai.yaml`` for OpenAI Codex in every skill folder:

- Codex ignores ``disable-model-invocation``. Its equivalent is
  ``policy.allow_implicit_invocation: false``, so user-invoked skills stay out of the model's
  catalog and start only when someone types ``$skill-name``.
- ``interface.display_name``, ``short_description`` and ``default_prompt`` drive the Codex UI.

Usage:
  python3 tools/gen_agent_files.py           # write / refresh the files
  python3 tools/gen_agent_files.py --check   # exit 1 if any file is missing or stale (CI)
"""
