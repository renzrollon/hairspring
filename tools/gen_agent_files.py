_KEY = re.compile(r"^(name|disable-model-invocation|user-invocable):\s*['\"]?([^'\"#\n]+?)['\"]?\s*$")
_INVOCATION = re.compile(r"^\s+invocation:\s*['\"]?(\w+)")


def parse(skill_md: Path) -> dict:
    text = skill_md.read_text(encoding="utf-8")
    end = text.find("\n---", 3)
    meta: dict = {}
    for line in text[3:end].splitlines():
        m = _KEY.match(line)
        if m:
            meta[m.group(1)] = m.group(2).strip()
        m = _INVOCATION.match(line)
        if m:
            meta["invocation"] = m.group(1)
    title = re.search(r"^# (.+)$", text[end:], re.MULTILINE)
    meta["title"] = title.group(1).strip() if title else skill_md.parent.name
    return meta


def q(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(meta: dict) -> str:
    name = meta.get("name") or ""
    short, prompt = CODEX.get(name, (meta["title"][:64], f"Use ${name} for this task."))
    implicit = meta.get("disable-model-invocation", "").lower() != "true"
    return (
        HEADER
        + "interface:\n"
        + f"  display_name: {q(meta['title'])}\n"
        + f"  short_description: {q(short)}\n"
        + f"  default_prompt: {q(prompt)}\n"
        + "policy:\n"
        + f"  allow_implicit_invocation: {'true' if implicit else 'false'}\n"
    )


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if any generated file is missing or stale")
    args = ap.parse_args(argv)
    problems = []
    count = 0
    for skill_md in sorted((ROOT / "skills").glob("*/*/SKILL.md")):
        meta = parse(skill_md)
        name = meta.get("name", "")
        if name in CODEX:
            short = CODEX[name][0]
            if not 25 <= len(short) <= 64:
                problems.append(f"{name}: short_description must be 25-64 chars ({len(short)})")
        else:
            problems.append(f"{name}: no Codex short description in tools/gen_agent_files.py")
        out = skill_md.parent / "agents" / "openai.yaml"
        content = render(meta)
        count += 1
        if args.check:
            if not out.is_file() or out.read_text(encoding="utf-8") != content:
                problems.append(f"{out.relative_to(ROOT)}: missing or stale (run tools/gen_agent_files.py)")
        else:
            out.parent.mkdir(exist_ok=True)
            out.write_text(content, encoding="utf-8")
    for p in problems:
        print(p, file=sys.stderr)
    if not args.check:
        print(f"wrote agents/openai.yaml for {count} skills")
    return 1 if problems and args.check else 0


if __name__ == "__main__":
    sys.exit(main())
