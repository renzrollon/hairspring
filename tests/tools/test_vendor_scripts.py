def vendor(vs, root, *argv):
    return vs.main(["--root", str(root), "-q", *argv])


def test_vendors_with_header_shebang_and_exec_bit(vs, root):
    assert vendor(vs, root) == 0
    script = root / "skills/validation/requirement-linter/scripts/lint_requirements.py"
    lines = script.read_text(encoding="utf-8").splitlines()
    assert lines[0] == "#!/usr/bin/env python3"
    assert lines[1] == ("# VENDORED from packages/re-lint/src/re_lint/lint.py by tools/vendor_scripts.py; "
                        "do not edit.")
    assert lines[2].startswith("# ")
    assert "\n".join(lines[3:]) + "\n" == (PKG / "lint.py").read_text(encoding="utf-8").split("\n", 1)[1]
    helper = root / "skills/validation/requirement-linter/scripts/reqio.py"
    assert "VENDORED from packages/re-lint/src/re_lint/reqio.py" in helper.read_text(encoding="utf-8")
    assert (root / "skills/specification/requirement-phrasing/scripts/lint_requirements.py").is_file()
    assert (root / "skills/_primitives/re-ids/scripts/re_ids.py").is_file()
    assert (root / "skills/_primitives/re-ids/scripts/reqio.py").is_file()
    assert (root / "skills/foundations/re-setup/assets/schema.json").read_text() == SCHEMA.read_text()
    if os.name == "posix":
        assert script.stat().st_mode & stat.S_IXUSR and helper.stat().st_mode & stat.S_IXUSR


