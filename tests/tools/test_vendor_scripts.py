def test_map_matches_the_contract():
    contract = (REPO_ROOT / "docs/tooling-contract.md").read_text(encoding="utf-8")
    from tools_helpers import load_tool
    vs = load_tool("vendor_scripts")
    for module, target, skills in vs.VENDOR_MAP:
        row = f"| `re_lint/{module}` | `scripts/{target}` | " + ", ".join(f"`{s}`" for s in skills) + " |"
        assert row in contract, row
    assert "| `skills/_primitives/re-templates/assets/schema.json` | `assets/schema.json` | " + \
        ", ".join(f"`{s}`" for s in vs.SCHEMA_TARGETS) + " |" in contract
