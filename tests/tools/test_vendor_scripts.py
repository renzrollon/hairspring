def test_vendored_scripts_run_standalone_from_any_cwd(vs, root, tmp_path):
    vendor(vs, root)
    scripts = root / "skills/validation/requirement-linter/scripts"
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    reqs = elsewhere / "requirements.csv"
    reqs.write_text("ID,Type,Text,Source,Priority,Status,Rationale\n"
                    "R-001,F,The app shall be fast.,S-01,must,draft,x\n", encoding="utf-8")
    for args in (["--help"], [str(reqs)]):
        proc = subprocess.run([sys.executable, str(scripts / "lint_requirements.py"), *args],
                              cwd=elsewhere, capture_output=True, text=True)
        assert proc.returncode == (0 if args == ["--help"] else 1), proc.stderr
    assert "weak-word R-001" in proc.stdout
    ids_script = root / "skills/_primitives/re-ids/scripts/re_ids.py"
    proc = subprocess.run([sys.executable, str(ids_script), "next", "--workspace", str(elsewhere), "--no-git"],
                          cwd=tmp_path, capture_output=True, text=True)
    assert (proc.returncode, proc.stdout) == (0, "R-002\n")
    if os.name == "posix":
        proc = subprocess.run([str(scripts / "lint_requirements.py"), "--list-rules"], cwd=elsewhere,
                              capture_output=True, text=True)
        assert proc.returncode == 0 and "register-drift" in proc.stdout


