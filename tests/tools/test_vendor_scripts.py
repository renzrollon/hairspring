def test_check_detects_drift(vs, root, capsys):
    vendor(vs, root)
    copy = root / "skills/_primitives/re-ids/scripts/re_ids.py"
    copy.write_text(copy.read_text(encoding="utf-8") + "# local edit\n", encoding="utf-8")
    (root / "skills/foundations/re-setup/assets/schema.json").unlink()
    rules = root / "skills/validation/requirement-linter/references/rules.md"
    rules.write_text("hand edited\n", encoding="utf-8")
    capsys.readouterr()
    assert vendor(vs, root, "--check") == 1
    out = capsys.readouterr().out
    assert "stale: skills/_primitives/re-ids/scripts/re_ids.py" in out
    assert "missing: skills/foundations/re-setup/assets/schema.json" in out
    assert "stale: skills/validation/requirement-linter/references/rules.md" in out
    vendor(vs, root)
    assert vendor(vs, root, "--check") == 0


