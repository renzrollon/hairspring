#!/usr/bin/env python3
"""Scaffold an OpenSpec change folder (or a spec-kit spec.md) from agreed requirements.

Usage::

    re-lint openspec CHANGE_NAME [--ids R-001,R-002 | --status agreed] [--target openspec|spec-kit]
                     [--out DIR] [--force] [--allow-tbd] [--skip-blocked] [--capability NAME]
                     [--date YYYY-MM-DD] [--title TEXT]

OpenSpec (default target) writes ``<out>/openspec/changes/<change>/``:

* ``.openspec.yaml``: ``schema: spec-driven``, ``created``, ``x-re-skills-source``, ``x-re-skills-ids``;
* ``proposal.md``: Why (drafted from the rationales), What Changes, Capabilities (new/modified),
  Constraints and Quality Requirements (every Type Q and C row, verbatim), Impact, Not in this
  change, Traceability;
* ``tasks.md``: one group per capability, then "Quality requirements and constraints"; every task
  ends with its R-IDs;
* ``specs/<capability>/spec.md``: ``## Purpose`` (new capabilities), ``## ADDED Requirements`` and,
  for IDs already in ``openspec/specs/``, ``## MODIFIED Requirements`` with the existing header.

Each functional requirement (Type F, or empty Type for stories) becomes
``### Requirement: R-012 <Title>`` followed by ``<!-- R-012 -->`` and the text with ``shall``/``must``
upper-cased (``should``/``may`` only when there is no ``shall``/``must``). Scenarios come from the
acceptance criteria ``R-012.ACn`` in ``stories/*.md`` (bold-label blocks with Given/When/Then
bullets, table rows, or "R-012.AC1: Given ..., when ..., then ..." lines). Without acceptance
criteria, one scenario ``R-012 main case (derived from the requirement text)`` is derived from
the EARS text: WHILE/WHERE -> GIVEN, WHEN/IF -> WHEN, the main clause -> THEN.

Capability: ``--capability`` for all rows; else a ``cap:<name>`` entry in ``Tags``; else the
change name without a leading ``add-``, ``update-``, ``change-``, ``remove-`` or ``fix-``. An ID
already in ``openspec/specs/<capability>/spec.md`` keeps that capability.

spec-kit (``--target spec-kit``) writes ``<out>/specs/<change>/spec.md`` in the spec-kit template:
one user story per functional requirement (priority must/should/could -> P1/P2/P3) with numbered
acceptance scenarios, Functional Requirements and Constraints keyed by R-ID, quality requirements
under Measurable Outcomes, and the rows left out under Assumptions.

Selection: ``--ids`` (exactly those) or ``--status`` (default ``agreed``). Withdrawn, rejected and
deferred rows and ``Priority=wont`` never go across. The gate refuses (exit 1, nothing written)
when a selected row has ``TBD``/``TBC``/``??``/``XXX`` in any attribute or acceptance criterion
(``--allow-tbd`` hands it off anyway) or when a functional requirement has neither an acceptance
criterion nor a WHEN/IF/WHILE/WHERE clause; ``--skip-blocked`` leaves blocked rows out and lists
them under "Not in this change". An existing change folder (or spec-kit spec) is never
overwritten without ``--force``.

Exit codes: 0 written, 1 refused (gate, existing folder, nothing to hand off), 2 usage error.
"""
