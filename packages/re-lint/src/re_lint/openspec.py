def _capability_for(row: reqio.Row, change: str, forced: Optional[str]) -> str:
    if forced:
        return forced
    for token in re.split(r"[\s,;]+", row.get_str("Tags")):
        if token.lower().startswith("cap:") and len(token) > 4:
            value = token[4:].strip().lower()
            return value if _CAP_PATH.match(value) else slugify(value)
    for prefix in VERB_PREFIXES:
        if change.startswith(prefix) and len(change) > len(prefix):
            return change[len(prefix):]
    return change


def _trace_code(ws: Path, ids: Sequence[str]) -> "OrderedDict[str, List[str]]":
    path = ws / "trace" / "trace.csv"
    out: "OrderedDict[str, List[str]]" = OrderedDict()
    if not path.is_file():
        return out
    try:
        table = reqio.read_table(path)
    except (OSError, UnicodeDecodeError, ValueError):
        return out
    wanted = set(ids)
    for row in table.rows:
        rid = row.get_str("From").split(".AC", 1)[0]
        if rid in wanted and row.get_str("ToType") == "code":
            out.setdefault(row.get_str("To"), [])
            if rid not in out[row.get_str("To")]:
                out[row.get_str("To")].append(rid)
    return out


def cmd_openspec(args: argparse.Namespace) -> int:
    ws, schema = _workspace(args)
    change = args.change
    if not _KEBAB.match(change):
        raise UsageError(f"change name {change!r} must be kebab-case (try {slugify(change) or 'add-feature'!r})")
    if args.capability and not _CAP_PATH.match(args.capability):
        raise UsageError(f"--capability {args.capability!r} must be a kebab-case path (e.g. voucher-redemption)")
    date = args.date or _dt.date.today().isoformat()
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", date):
        raise UsageError(f"--date {date!r} must be YYYY-MM-DD")
    root = Path(args.out).resolve() if args.out else reqio.find_repo_root(ws).resolve()
    register = os.path.relpath(ws / "requirements.csv", root).replace(os.sep, "/")
    try:
        all_rows = reqio.read_requirements(reqio.requirement_files(ws), schema)
    except UnicodeDecodeError as exc:
        raise UsageError(f"cannot read the requirement registers as UTF-8: {exc}") from exc
    rows_by_id: "OrderedDict[str, reqio.Row]" = OrderedDict()
    for row in all_rows:
        rows_by_id.setdefault(row.get_str("ID"), row)
    if not rows_by_id:
        raise UsageError(f"no requirements found in {ws}")
    named = bool(args.ids)
    if named:
        wanted = _split_list(args.ids)
        unknown = [i for i in wanted if i not in rows_by_id]
        if unknown:
            raise UsageError(f"unknown requirement ID(s): {', '.join(unknown)}")
        keep = set(wanted)
        selected = [r for rid, r in rows_by_id.items() if rid in keep]
    else:
        statuses = {s.lower() for s in _split_list(args.status or ["agreed"])}
        selected = [r for r in rows_by_id.values() if r.get_str("Status").lower() in statuses]

    if args.target == "openspec":
        dest = root / "openspec" / "changes" / change
        exists = dest.exists()
    else:
        dest = root / "specs" / change
        exists = (dest / "spec.md").exists()
    if exists and not args.force:
        raise Refusal(f"{dest} already exists; pass --force to overwrite the generated files "
                      "(never on a change whose tasks.md has ticked boxes)")

    acs = parse_acceptance_criteria(ws, schema)
    accepted, blocked, left_out, _ = gate(selected, acs, named, args.allow_tbd)
    if blocked and not args.skip_blocked:
        print("| ID | Check | Finding | Action |")
        print("| --- | --- | --- | --- |")
        for rid, check, finding, action in blocked:
            print(f"| {rid} | {check} | {finding} | {action} |")
        raise Refusal(f"the hand-off gate blocked {len(blocked)} requirement(s); nothing was written "
                      "(fix them, or pass --skip-blocked to leave them out)")
    left_out = [(rid, f"{finding} ({check})") for rid, check, finding, _ in blocked] + left_out
    if not accepted:
        how = f"--ids {','.join(_split_list(args.ids))}" if named else f"--status {','.join(_split_list(args.status or ['agreed']))}"
        details = "; ".join(f"{rid}: {reason}" for rid, reason in left_out)
        raise Refusal(f"nothing to hand off for {how}" + (f" ({details})" if details else ""))

    id_pattern = re.escape(str(((schema.get("ids") or {}).get("requirement") or {}).get("prefix", "R-"))) + r"\d+"
    existing = existing_specs(root, id_pattern) if args.target == "openspec" else {}
    warnings: List[str] = []
    verification = {r.get_str("ID"): _verification(r, _verification_csv(ws)) for r in accepted}
    scenarios = {r.get_str("ID"): scenarios_for(r, acs) for r in accepted}
    capabilities: "OrderedDict[str, List[reqio.Row]]" = OrderedDict()
    for row in accepted:
        rid = row.get_str("ID")
        text = row.get_str("Text")
        upper = upcase_obligation(text)
        if not re.search(r"\b(SHALL|MUST)\b", upper):
            warnings.append(f"{rid}: no SHALL/MUST in the text; `openspec validate --strict` fails on it")
        if len(f"<!-- {rid} -->\n{_one_line(upper)}") > MAX_TEXT:
            warnings.append(f"{rid}: requirement text over {MAX_TEXT} characters; split it with requirement-phrasing")
        for sc in scenarios[rid]:
            kws = {k for k, _ in sc["steps"]}
            if not kws & {"WHEN", "GIVEN"} or "THEN" not in kws:
                warnings.append(f"{rid}: scenario {sc['id']} lacks a WHEN/GIVEN or THEN step")
        if _row_type(row) != "F":
            continue
        cap = _capability_for(row, change, args.capability)
        if rid in existing:
            if existing[rid][0] != cap:
                warnings.append(f"{rid}: already in openspec/specs/{existing[rid][0]}; using that capability "
                                f"instead of {cap}")
            cap = existing[rid][0]
        capabilities.setdefault(cap, []).append(row)
    for rid, changes in ids_in_other_changes(root, change, id_pattern).items():
        if rid in scenarios:
            warnings.append(f"{rid}: also in open change(s) {', '.join(changes)}; they collide at archive")
    existing_caps = {cap for cap, _ in existing.values()}
    specs_dir = root / "openspec" / "specs"
    existing_caps |= {c for c in capabilities if (specs_dir / c / "spec.md").is_file()}
    plan = {"rows": accepted, "scenarios": scenarios, "capabilities": capabilities, "left_out": left_out,
            "verification": verification, "existing": existing, "existing_caps": existing_caps,
            "code": _trace_code(ws, [r.get_str("ID") for r in accepted])}

    if args.target == "openspec":
        files = render_openspec(change, date, register, plan)
        if args.force and dest.is_dir():
            for old in dest.glob("specs/**/spec.md"):
                rel = old.relative_to(dest).as_posix()
                try:
                    stale = rel not in files and GENERATED_MARK in old.read_text(encoding="utf-8")
                except (OSError, UnicodeDecodeError):
                    stale = False
                if stale:
                    old.unlink()
            tasks = dest / "tasks.md"
            if tasks.is_file() and re.search(r"^\s*- \[[xX]\]", tasks.read_text(encoding="utf-8"), re.M):
                warnings.append("tasks.md had ticked boxes; --force replaced it")
        for rel, text in files.items():
            _write_text(dest / rel, text)
        written = list(files)
        next_step = f"openspec validate {change} --strict --no-interactive"
    else:
        title = args.title or (re.sub(r"^\d+-", "", change).replace("-", " ").capitalize() or change)
        text = render_speckit(change, title, date, register, plan)
        markers = text.count("[NEEDS CLARIFICATION")
        if markers > 3:
            warnings.append(f"{markers} [NEEDS CLARIFICATION] markers; spec-kit expects at most 3 "
                            "(run clarifying-questions first)")
        _write_text(dest / "spec.md", text)
        written = ["spec.md"]
        next_step = f"set SPECIFY_FEATURE_DIRECTORY=specs/{change} (or use branch {change}) and run /speckit.plan"

    rel_dest = os.path.relpath(dest, Path.cwd()) if str(dest).startswith(str(Path.cwd())) else str(dest)
    print(f"wrote {rel_dest}/ ({', '.join(written)})")
    print(f"handed off: {', '.join(r.get_str('ID') for r in accepted)}")
    for rid, reason in left_out:
        print(f"note: {rid}: {reason}")
    for warning in warnings:
        print(f"warning: {warning}")
    print(f"next: {next_step}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="to_openspec.py",
        description="Hand agreed requirements to coding agents: write an OpenSpec change folder "
                    "(proposal.md, tasks.md, specs/<capability>/spec.md) or a spec-kit spec.md, keeping "
                    "every R-ID as an anchor.",
        epilog="Exit codes: 0 written, 1 refused (gate finding, existing folder, nothing selected), 2 usage error.",
    )
    parser.add_argument("change", metavar="CHANGE_NAME",
                        help="kebab-case change name (OpenSpec: add-voucher-redemption; spec-kit: 004-voucher-redemption)")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--ids", metavar="ID", nargs="+", action="extend", help="exactly these requirement IDs")
    group.add_argument("--status", metavar="S", nargs="+", action="extend",
                       help="every requirement with these statuses (default: agreed)")
    parser.add_argument("--target", choices=("openspec", "spec-kit"), default="openspec")
    parser.add_argument("--out", metavar="DIR", help="folder holding openspec/ or specs/ (default: the repo root)")
    parser.add_argument("--force", action="store_true", help="overwrite an existing change folder or spec")
    parser.add_argument("--allow-tbd", action="store_true", help="hand off rows with TBD/TBC/??/XXX placeholders")
    parser.add_argument("--skip-blocked", action="store_true",
                        help="leave rows the gate blocks out (listed under 'Not in this change') instead of refusing")
    parser.add_argument("--capability", metavar="NAME", help="put every functional requirement in this capability")
    parser.add_argument("--date", metavar="YYYY-MM-DD", help="creation date written into the files (default today)")
    parser.add_argument("--title", metavar="TEXT", help="spec-kit feature title (default: from the change name)")
    parser.add_argument("--workspace", metavar="DIR", help="workspace folder (default: <repo root>/requirements)")
    parser.add_argument("--schema", metavar="FILE", help="schema.json to use (default: <workspace>/schema.json)")
    return parser


def run(args: argparse.Namespace) -> int:
    try:
        return cmd_openspec(args)
    except Refusal as exc:
        print(f"refused: {exc}", file=sys.stderr)
        return 1
    except (UsageError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return run(args)


if __name__ == "__main__":
    raise SystemExit(main())
