# --------------------------------------------------------------------------- helpers


def _workspace(args: argparse.Namespace) -> Tuple[Path, Dict]:
    schema_path = getattr(args, "schema", None)
    if schema_path and not Path(schema_path).is_file():
        raise UsageError(f"schema file not found: {schema_path}")
    if getattr(args, "workspace", None):
        ws = Path(args.workspace).resolve()
    else:
        base = reqio.load_schema(schema_path) if schema_path else None
        ws = reqio.find_workspace(".", base).resolve()
    return ws, reqio.load_schema(schema_path, workspace=ws)


def _split_list(values: Optional[Sequence[str]]) -> List[str]:
    out: List[str] = []
    for value in values or []:
        out.extend(v for v in re.split(r"[,\s]+", value) if v)
    return out


def _id_key(value: str) -> Tuple:
    match = re.match(r"^(.*?)(\d+)(.*)$", value or "")
    if not match:
        return (value or "", -1, "")
    return (match.group(1), int(match.group(2)), match.group(3))


def _one_line(text: str) -> str:
    return " ".join((text or "").split())


def _md_cell(value: object) -> str:
    return _one_line(str(value if value is not None else "")).replace("|", "\\|")


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def slugify(text: str) -> str:
    return re.sub(r"-{2,}", "-", re.sub(r"[^a-z0-9]+", "-", (text or "").lower())).strip("-")


def upcase_obligation(text: str) -> str:
    """``shall``/``must`` -> upper case; ``should``/``may`` only when neither is present."""
    if re.search(r"\b(?:shall|must)\b", text, re.I):
        return re.sub(r"\b(shall|must)\b", lambda m: m.group(1).upper(), text, flags=re.I)
    return re.sub(r"\b(should|may)\b", lambda m: m.group(1).upper(), text, flags=re.I)


def short_title(row: reqio.Row) -> str:
    title = _one_line(row.get_str("Title"))
    if title:
        return title
    words = _one_line(row.get_str("Text")).split()[:8]
    return " ".join(words).rstrip(".,;:")


def _row_type(row: reqio.Row) -> str:
    t = row.get_str("Type").upper()
    return t if t in ("Q", "C") else "F"


