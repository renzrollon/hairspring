def ears_steps(text: str) -> Optional[List[Tuple[str, str]]]:
    """GIVEN/WHEN/THEN steps derived from an EARS sentence, or ``None`` for ubiquitous text."""
    t = _one_line(text)
    verb = re.search(r"\b(shall|must|should|may)\b", t, re.I)
    if not verb:
        return None
    comma = t[:verb.start()].rfind(",")
    if comma == -1:
        return None
    cond, main = t[:comma], t[comma + 1:].strip()
    main = re.sub(r"^then\s+", "", main, flags=re.I)
    pieces = re.split(r"(?:^|,\s*)(WHILE|WHERE|WHEN|IF)\s+", cond, flags=re.I)
    if pieces[0].strip() or len(pieces) < 3:
        return None
    steps: List[Tuple[str, str]] = []
    for keyword, clause in zip(pieces[1::2], pieces[2::2]):
        clause = clause.strip().rstrip(",").strip()
        if not clause:
            return None
        steps.append(("GIVEN" if keyword.upper() in ("WHILE", "WHERE") else "WHEN", clause))
    steps.append(("THEN", upcase_obligation(main)))
    return steps


_INLINE_SPLIT = re.compile(r"(?:^|[,;]\s*|\.\s+)\b(given|when|then)\b\s*", re.I)
_INLINE_SPLIT_LOOSE = re.compile(r"(?:^|\s+)\b(given|when|then)\b\s*", re.I)
_AND_SPLIT = re.compile(r",?\s+and\s+(?=(?:the|a|an|its|their|it|they|no|this|that|his|her)\b)", re.I)


def inline_steps(text: str) -> Tuple[str, List[Tuple[str, str]]]:
    """Leading label and steps of "Given ..., when ..., then ... and ..." text."""
    body = _one_line(text)
    parts = _INLINE_SPLIT.split(body)
    if len(parts) < 3 or not any(p.lower() == "then" for p in parts[1::2]):
        loose = _INLINE_SPLIT_LOOSE.split(body)
        if len(loose) > len(parts):
            parts = loose
    label = parts[0].strip(" :-.") if parts else ""
    steps: List[Tuple[str, str]] = []
    for keyword, clause in zip(parts[1::2], parts[2::2]):
        clause = clause.strip().rstrip(".,;").strip()
        if not clause:
            continue
        keyword = keyword.upper()
        if keyword == "THEN":
            pieces = _AND_SPLIT.split(clause)
            steps.append(("THEN", pieces[0].strip()))
            steps.extend(("AND", p.strip().rstrip(".")) for p in pieces[1:] if p.strip())
        else:
            steps.append((keyword, clause))
    return label, steps


def when_name(steps: Sequence[Tuple[str, str]]) -> str:
    clause = next((c for k, c in steps if k == "WHEN"), steps[0][1] if steps else "")
    words = clause.split()[:8]
    if words and words[0].lower() in ("the", "a", "an"):
        words = words[1:]
    name = " ".join(words).rstrip(".,;:")
    return name[:1].upper() + name[1:]


def parse_acceptance_criteria(ws: Path, schema: Dict) -> Dict[str, List[Dict]]:
    """Acceptance criteria per base requirement ID, from ``<workspace>/stories/*.md``."""
    spec = (schema.get("ids") or {}).get("requirement") or {"prefix": "R-", "digits": 3}
    ac = rf"({re.escape(str(spec.get('prefix', 'R-')))}\d{{{int(spec.get('digits', 3))},}}\.AC(\d+))"
    label_re = re.compile(rf"^\s*(?:[-*+]\s+)?(?:\*\*|__)\s*{ac}\s*[:.\u2013-]?\s*(.*?)\s*(?:\*\*|__)(.*)$")
    inline_re = re.compile(rf"^\s*(?:[-*+]\s+|\d+\.\s+)?{ac}\s*[:.\u2013-]?\s*(.+)$")
    found: Dict[str, Dict] = {}
    stories = ws / "stories"
    files = sorted(stories.glob("*.md")) if stories.is_dir() else []
    for path in files:
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        lines = text.splitlines()
        in_fence = False
        i = 0
        while i < len(lines):
            line = lines[i]
            if line.strip().startswith(("```", "~~~")):
                in_fence = not in_fence
                i += 1
                continue
            if in_fence or line.lstrip().startswith("|"):
                i += 1
                continue
            m = label_re.match(line)
            if m:
                ac_id, number, name, rest = m.group(1), int(m.group(2)), m.group(3).strip(), m.group(4)
                raw = [name, rest]
                j = i + 1
                if re.search(r"\b(given|when|then)\b", rest, re.I):
                    label, steps = inline_steps(rest)
                else:
                    label, steps = "", []
                    if j < len(lines) and not lines[j].strip():
                        j += 1  # one blank line between the label and its bullets
                    while j < len(lines):
                        step = _STEP.match(lines[j])
                        if step:
                            steps.append((step.group(1).upper(), step.group(2).strip()))
                            raw.append(step.group(2))
                        elif _FLAG.match(lines[j]):
                            raw.append(lines[j])
                        else:
                            break
                        j += 1
                found.setdefault(ac_id, {"id": ac_id, "number": number, "name": name or label,
                                         "steps": steps, "raw": " ".join(raw), "file": str(path), "line": i + 1})
                i = j
                continue
            m = inline_re.match(line)
            if m and re.search(r"\b(given|when|then)\b", m.group(3), re.I):
                label, steps = inline_steps(m.group(3))
                found.setdefault(m.group(1), {"id": m.group(1), "number": int(m.group(2)), "name": label,
                                              "steps": steps, "raw": m.group(3), "file": str(path), "line": i + 1})
            i += 1
        try:
            tables = reqio.read_tables(path)
        except (OSError, UnicodeDecodeError, ValueError):
            tables = []
        for table in tables:
            if "ID" not in table.columns:
                continue
            others = [c for c in table.columns if c != "ID"]
            text_col = next((c for c in others if re.search(r"criteri|scenario|given|text|ac\b", c, re.I)),
                            others[0] if others else None)
            if text_col is None:
                continue
            for row in table.rows:
                m = re.match(rf"^{ac}$", row.get_str("ID"))
                if not m:
                    continue
                label, steps = inline_steps(row.get_str(text_col))
                found.setdefault(m.group(1), {"id": m.group(1), "number": int(m.group(2)), "name": label,
                                              "steps": steps, "raw": row.get_str(text_col),
                                              "file": str(path), "line": row.line})
    out: Dict[str, List[Dict]] = {}
    for item in found.values():
        out.setdefault(item["id"].split(".AC", 1)[0], []).append(item)
    for items in out.values():
        items.sort(key=lambda a: a["number"])
    return out


