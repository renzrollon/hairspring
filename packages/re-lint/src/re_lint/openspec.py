def existing_specs(root: Path, id_pattern: str) -> Dict[str, Tuple[str, str]]:
    """``ID -> (capability path, exact requirement name)`` from ``openspec/specs/**/spec.md``."""
    specs_dir = root / "openspec" / "specs"
    out: Dict[str, Tuple[str, str]] = {}
    if not specs_dir.is_dir():
        return out
    header_re = re.compile(r"^###\s*Requirement:\s*(.+?)\s*$")
    for path in sorted(specs_dir.rglob("spec.md")):
        cap = path.parent.relative_to(specs_dir).as_posix()
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeDecodeError):
            continue
        current: Optional[str] = None
        for line in lines:
            m = header_re.match(line)
            if m:
                current = m.group(1)
                first = re.match(rf"^({id_pattern})\b", current)
                if first:
                    out.setdefault(first.group(1), (cap, current))
                continue
            anchor = re.search(rf"<!--\s*({id_pattern})\s*-->", line)
            if anchor and current:
                out.setdefault(anchor.group(1), (cap, current))
    return out


def ids_in_other_changes(root: Path, change: str, id_pattern: str) -> Dict[str, List[str]]:
    changes = root / "openspec" / "changes"
    out: Dict[str, List[str]] = {}
    if not changes.is_dir():
        return out
    for folder in sorted(p for p in changes.iterdir() if p.is_dir() and p.name not in (change, "archive")):
        for path in folder.rglob("*.md"):
            try:
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            for rid in set(re.findall(rf"<!--\s*({id_pattern})\s*-->", text)):
                out.setdefault(rid, [])
                if folder.name not in out[rid]:
                    out[rid].append(folder.name)
    return out


# --------------------------------------------------------------------------- selection and gate


def _verification(row: reqio.Row, extra: Dict[str, str]) -> str:
    return (row.get_str("Verification") or extra.get(row.get_str("ID"), "")).lower()


def _verification_csv(ws: Path) -> Dict[str, str]:
    path = ws / "verification.csv"
    out: Dict[str, str] = {}
    if not path.is_file():
        return out
    try:
        table = reqio.read_table(path)
    except (OSError, UnicodeDecodeError, ValueError):
        return out
    col = next((c for c in table.columns if c.lower() in ("verification", "method", "verification method")), None)
    if col:
        for row in table.rows:
            if row.get_str("ID") and row.get_str(col):
                out.setdefault(row.get_str("ID"), row.get_str(col))
    return out


def gate(rows: Sequence[reqio.Row], acs: Dict[str, List[Dict]], named: bool, allow_tbd: bool
         ) -> Tuple[List[reqio.Row], List[Tuple[str, str, str, str]], List[Tuple[str, str]], List[str]]:
    """Rows that go across, blocked rows (id, check, finding, action), left-out rows, notes."""
    accepted: List[reqio.Row] = []
    blocked: List[Tuple[str, str, str, str]] = []
    left_out: List[Tuple[str, str]] = []
    notes: List[str] = []
    for row in rows:
        rid = row.get_str("ID")
        status = row.get_str("Status").lower()
        if status in NEVER_STATUSES:
            left_out.append((rid, f"Status={status} (never handed off)"))
            continue
        if row.get_str("Priority").lower() == "wont":
            left_out.append((rid, "Priority=wont (never handed off)"))
            continue
        tbd_cols = [c for c, v in row.items() if c != "ID" and _TBD.search(str(v or ""))]
        tbd_cols += [a["id"] for a in acs.get(rid, []) if _TBD.search(a["raw"])]
        if tbd_cols and not allow_tbd:
            blocked.append((rid, "G2", f"open placeholder in {', '.join(tbd_cols)}",
                            "answer the open question, or pass --allow-tbd"))
            continue
        if _row_type(row) == "F" and not acs.get(rid) and ears_steps(row.get_str("Text")) is None:
            blocked.append((rid, "G4", "no acceptance criterion and no WHEN/IF/WHILE/WHERE clause",
                            "write an acceptance criterion (user-story-refiner, testability-check)"))
            continue
        if tbd_cols:
            left_out.append((rid, f"in this change despite open placeholder in {', '.join(tbd_cols)} (--allow-tbd)"))
        if status in DRAFT_STATUSES:
            how = "named by --ids" if named else "selected by --status"
            left_out.append((rid, f"in this change with Status={status} ({how}); confirm the approval"))
        accepted.append(row)
        if status in DRAFT_STATUSES:
            notes.append(rid)
    return accepted, blocked, left_out, notes


# --------------------------------------------------------------------------- OpenSpec rendering


def scenarios_for(row: reqio.Row, acs: Dict[str, List[Dict]]) -> List[Dict]:
    rid = row.get_str("ID")
    out = []
    for ac in acs.get(rid, []):
        if not ac["steps"]:
            continue
        out.append({"id": ac["id"], "name": f"{ac['id']} {ac['name'] or when_name(ac['steps'])}".strip(),
                    "steps": ac["steps"], "derived": False})
    if not out:
        steps = ears_steps(row.get_str("Text"))
        if steps:
            out.append({"id": rid, "name": f"{rid} main case (derived from the requirement text)",
                        "steps": steps, "derived": True})
    return out


def _requirement_block(row: reqio.Row, name: str, scenarios: Sequence[Dict]) -> List[str]:
    rid = row.get_str("ID")
    out = [f"### Requirement: {name}", f"<!-- {rid} -->", upcase_obligation(_one_line(row.get_str("Text"))), ""]
    for sc in scenarios:
        out.append(f"#### Scenario: {sc['name']}")
        out += [f"- **{kw}** {text}" for kw, text in sc["steps"]]
        out.append("")
    return out


def _verify_words(method: str) -> str:
    return {"inspection": "inspection", "analysis": "analysis", "demonstration": "demonstration"}.get(method, "test")


def render_openspec(change: str, date: str, register: str, plan: Dict) -> Dict[str, str]:
    files: "OrderedDict[str, str]" = OrderedDict()
    ids = [r.get_str("ID") for r in plan["rows"]]
    files[".openspec.yaml"] = (f"schema: spec-driven\ncreated: {date}\nx-re-skills-source: {register}\n"
                               f"x-re-skills-ids: [{', '.join(ids)}]\n")
    functional = [r for r in plan["rows"] if _row_type(r) == "F"]
    quality = [r for r in plan["rows"] if _row_type(r) != "F"]
    caps: "OrderedDict[str, List[reqio.Row]]" = plan["capabilities"]
    task_no: Dict[str, str] = {}
    lands: Dict[str, str] = {}
    tasks = ["# Tasks", "",
             f"<!-- {GENERATED_MARK}. Every task ends with its R-IDs; cite them in commit messages and test "
             "names (test_r_<nnn>_...). -->", ""]
    group = 0
    for cap, rows in caps.items():
        group += 1
        tasks += [f"## {group}. {cap}", ""]
        for n, row in enumerate(rows, 1):
            rid = row.get_str("ID")
            scen = plan["scenarios"][rid]
            names = [s["id"] if not s["derived"] else f"{rid} main case" for s in scen]
            method = _verify_words(plan["verification"].get(rid, ""))
            how = "an automated test" if method == "test" else method
            noun = "scenario" if len(names) == 1 else "scenarios"
            tasks.append(f"- [ ] {group}.{n} Implement {rid} {short_title(row)}; verify by {how} for {noun} "
                         f"{', '.join(names)} ({rid})")
            task_no[rid] = f"{group}.{n}"
            lands[rid] = f"specs/{cap}/spec.md"
        tasks.append("")
    if quality:
        group += 1
        tasks += [f"## {group}. Quality requirements and constraints", ""]
        for n, row in enumerate(quality, 1):
            rid = row.get_str("ID")
            method = _verify_words(plan["verification"].get(rid, ""))
            tasks.append(f"- [ ] {group}.{n} Verify {rid} {short_title(row)} by {method} against proposal.md ({rid})")
            task_no[rid] = f"{group}.{n}"
            lands[rid] = "proposal.md"
        tasks.append("")
    files["tasks.md"] = "\n".join(tasks).rstrip("\n") + "\n"

    for cap, rows in caps.items():
        new_cap = cap not in plan["existing_caps"]
        added = [r for r in rows if r.get_str("ID") not in plan["existing"]]
        modified = [r for r in rows if r.get_str("ID") in plan["existing"]]
        out = [f"# Spec Delta: {cap}", "",
               f"<!-- {GENERATED_MARK} from {register} on {date}. Keep the R-IDs in headings; change "
               "requirement text in the register and re-export. -->", ""]
        if new_cap:
            label = cap.rsplit("/", 1)[-1].replace("-", " ")
            purpose = (f"{label[:1].upper()}{label[1:]}: {'; '.join(short_title(r) for r in rows)} "
                       f"({', '.join(r.get_str('ID') for r in rows)}).")
            if len(purpose) < 60:
                purpose += f" The requirement text is owned by `{register}`."
            out += ["## Purpose", "", purpose, ""]
        if added:
            out += ["## ADDED Requirements", ""]
            for row in added:
                rid = row.get_str("ID")
                out += _requirement_block(row, f"{rid} {short_title(row)}", plan["scenarios"][rid])
        if modified:
            out += ["## MODIFIED Requirements", ""]
            for row in modified:
                rid = row.get_str("ID")
                out += _requirement_block(row, plan["existing"][rid][1], plan["scenarios"][rid])
        files[f"specs/{cap}/spec.md"] = "\n".join(out).rstrip("\n") + "\n"

    rationales: List[str] = []
    for row in plan["rows"]:
        rationale = _one_line(row.get_str("Rationale"))
        if rationale and rationale not in rationales:
            rationales.append(f"{rationale.rstrip('.')} ({row.get_str('ID')}).")
    why = " ".join(rationales) or "These requirements are agreed in the requirement register."
    if len(why) < 50:
        why += " They are agreed in the requirement register and handed off for implementation."
    if len(why) > 1000:
        why = why[:996].rsplit(" ", 1)[0] + " ..."
    p = [f"# Proposal: {change}", "",
         f"<!-- {GENERATED_MARK} from {register} on {date}. R-IDs are trace anchors: keep them in commits and "
         "test names. Change requirement text in the register and re-export; do not edit it here. "
         "## Why is a draft from the rationales: confirm it with the requirement owner. -->", "",
         "## Why", "", why, "", "## What Changes", ""]
    p += [f"- {r.get_str('ID')} {short_title(r)} ({r.get_str('Priority') or 'no priority'})"
          for r in (functional or quality)]
    p += ["", "## Capabilities", "", "### New Capabilities", ""]
    new_caps = [c for c in caps if c not in plan["existing_caps"]]
    mod_caps = [c for c in caps if c in plan["existing_caps"]]
    p += [f"- `{c}`: {'; '.join(short_title(r) for r in caps[c])} ({', '.join(r.get_str('ID') for r in caps[c])})"
          for c in new_caps] or ["- None"]
    p += ["", "### Modified Capabilities", ""]
    p += [f"- `{c}`: {'; '.join(short_title(r) for r in caps[c])} ({', '.join(r.get_str('ID') for r in caps[c])})"
          for c in mod_caps] or ["- None"]
    p += ["", "## Constraints and Quality Requirements", ""]
    if quality:
        p += ["| ID | Type | Requirement | Source | Verification |", "| --- | --- | --- | --- | --- |"]
        p += [f"| {r.get_str('ID')} | {_row_type(r)} | {_md_cell(r.get_str('Text'))} | {_md_cell(r.get_str('Source'))} | "
              f"{_md_cell(plan['verification'].get(r.get_str('ID')) or 'TBD')} |" for r in quality]
    else:
        p.append("None.")
    p += ["", "## Impact", ""]
    for path, rids in plan["code"].items():
        p.append(f"- `{path}` ({', '.join(rids)}; from the trace matrix)")
    p += [f"- Register: `{register}`", "", "## Not in this change", ""]
    if plan["left_out"]:
        p += ["| ID | Reason |", "| --- | --- |"]
        p += [f"| {rid} | {_md_cell(reason)} |" for rid, reason in plan["left_out"]]
    else:
        p.append("None.")
    p += ["", "## Traceability", "", "| ID | Type | Priority | Status | Source | Lands in |",
          "| --- | --- | --- | --- | --- | --- |"]
    for r in plan["rows"]:
        rid = r.get_str("ID")
        p.append(f"| {rid} | {_row_type(r)} | {r.get_str('Priority')} | {r.get_str('Status')} | "
                 f"{_md_cell(r.get_str('Source'))} | {lands[rid]}; tasks {task_no[rid]} |")
    files["proposal.md"] = "\n".join(p) + "\n"
    order = [".openspec.yaml", "proposal.md", "tasks.md"]
    return OrderedDict(sorted(files.items(), key=lambda kv: (order.index(kv[0]) if kv[0] in order else 3, kv[0])))


# --------------------------------------------------------------------------- spec-kit rendering


def _clarify(text: str, register: str) -> str:
    return _TBD.sub(f"[NEEDS CLARIFICATION: value is TBD in {register}]", text)


def render_speckit(change: str, title: str, date: str, register: str, plan: Dict) -> str:
    rows = plan["rows"]
    functional = [r for r in rows if _row_type(r) == "F"]
    order = {"must": 0, "should": 1, "could": 2}
    stories = sorted(functional, key=lambda r: order.get(r.get_str("Priority").lower(), 3))
    ids = ", ".join(r.get_str("ID") for r in rows)
    out = [f"# Feature Specification: {title}", "", f"**Feature Branch**: `{change}`", "",
           f"**Created**: {date}", "", "**Status**: Draft", "",
           f"**Input**: Agreed requirements exported from `{register}` by re-skills to-openspec ({ids})", "",
           f"<!-- {GENERATED_MARK}. Requirement keys are the project's R-IDs instead of FR-nnn / SC-nnn, so "
           "commits, tests and the trace matrix keep matching. Change requirement text in the register and "
           "re-export. -->", "", "## User Scenarios & Testing *(mandatory)*", ""]
    story_no: Dict[str, int] = {}
    for n, row in enumerate(stories, 1):
        rid = row.get_str("ID")
        story_no[rid] = n
        prio = PRIORITY_P.get(row.get_str("Priority").lower(), "P3")
        scen = plan["scenarios"][rid]
        method = _verify_words(plan["verification"].get(rid, ""))
        method_text = {"test": "An automated test", "inspection": "Inspection", "analysis": "Analysis",
                       "demonstration": "A demonstration"}[method]
        first = scen[0]["id"] if scen and not scen[0]["derived"] else f"{rid} main case"
        out += [f"### User Story {n} - {short_title(row)} (Priority: {prio})", f"<!-- {rid} -->", "",
                f"{_clarify(_one_line(row.get_str('Text')), register)} ({rid})", "",
                f"**Why this priority**: {_clarify(_one_line(row.get_str('Rationale')), register) or 'Not stated in the register.'}",
                "", f"**Independent Test**: {method_text} of scenario {first}.", "", "**Acceptance Scenarios**:", ""]
        for k, sc in enumerate(scen, 1):
            words = ", ".join(f"**{kw.capitalize()}** {_clarify(text, register)}" for kw, text in sc["steps"])
            tag = f"{rid}, derived from the requirement text" if sc["derived"] else sc["id"]
            out.append(f"{k}. {words} ({tag})")
        out += ["", "---", ""]
    out += ["### Edge Cases", ""]
    edges = [r for r in stories if re.match(r"^\s*IF\b", r.get_str("Text"), re.I)]
    out += [f"- {r.get_str('ID')}: {short_title(r)} (see User Story {story_no[r.get_str('ID')]})" for r in edges] \
        or ["- No unwanted-behavior (IF ... THEN) requirement was selected for this feature."]
    out += ["", "## Requirements *(mandatory)*", "", "<!-- Keys are R-IDs from the register, not FR-nnn. -->", "",
            "### Functional Requirements", ""]
    out += [f"- **{r.get_str('ID')}**: {_clarify(upcase_obligation(_one_line(r.get_str('Text'))), register)}"
            for r in functional] or ["- No functional requirement was selected for this feature."]
    out += ["", "### Constraints", ""]
    out += [f"- **{r.get_str('ID')}**: {_clarify(_one_line(r.get_str('Text')), register)}"
            for r in rows if _row_type(r) == "C"] or ["- No constraint was selected for this feature."]
    out += ["", "## Success Criteria *(mandatory)*", "", "### Measurable Outcomes", ""]
    out += [f"- **{r.get_str('ID')}**: {_clarify(_one_line(r.get_str('Text')), register)}"
            for r in rows if _row_type(r) == "Q"] or ["- No quality requirement was selected for this feature."]
    out += ["", "## Assumptions", "", f"- Requirement text is owned by `{register}`; change it there and re-export."]
    out += [f"- Not in this feature: {rid} ({reason})" for rid, reason in plan["left_out"]]
    return "\n".join(out) + "\n"


