NEVER_STATUSES = {"withdrawn", "rejected", "deferred"}
DRAFT_STATUSES = {"draft", "proposed"}
VERB_PREFIXES = ("add-", "update-", "change-", "remove-", "fix-")
PRIORITY_P = {"must": "P1", "should": "P2", "could": "P3"}
MAX_TEXT = 500
GENERATED_MARK = "Generated by re-skills to-openspec"
_TBD = re.compile(r"(?i:\b(?:TBD|TBC)\b)|\?\?|\bXXX\b")
_KEBAB = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
_CAP_PATH = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*(?:/[a-z0-9]+(?:-[a-z0-9]+)*)*$")
_STEP = re.compile(r"^\s*[-*+]\s+(?:\*\*|__)?(Given|When|Then|And|But)(?::)?(?:\*\*|__)?:?\s+(.*)$", re.I)
_FLAG = re.compile(r"^\s*[-*+]\s+(?:\*\*|__)?(Flag|Note|Notes)\b", re.I)


